/*
 * spi_link.h
 *
 * Ведомый SPI к прибору K57. Пока - только проверка канала.
 *
 * Прибор раз в 50 мс шлёт 32 байта (16 слов по 16 бит, старший байт первым):
 *
 *   слово 0      0xA55A          - метка прибора
 *   слово 1      seq             - номер посылки
 *   слова 2..15  seq + i*0x0101  - узор
 *
 * Ведомый не может ответить в той же посылке, на которую отвечает: буфер
 * передачи загружается до того, как прибор опустит CS. Поэтому в ответ уходит
 * эхо ПРЕДЫДУЩЕЙ посылки с меткой 0x5AA5 в слове 0. Прибор сверяет эхо (POCI),
 * мы сверяем узор (PICO). Сторона прибора - INVERTOR_CCS/my_Files/wifi_link.c.
 *
 * «Есть данные» в этой проверке значит «ответ заряжен»: ножка опускается,
 * когда очередная транзакция готова, и поднимается по её окончании.
 */
#pragma once

#include <stdint.h>

typedef struct {
    uint32_t total;   /* завершённых транзакций */
    uint32_t ok;      /* метка и узор верны, номер на 1 больше прошлого */
    uint32_t noMagic; /* нет метки 0xA55A: сдвиг на бит или мусор на линии */
    uint32_t bad;     /* метка есть, узор искажён */
    uint32_t gap;     /* номер не подряд - посылка прошла мимо нас */
    uint32_t truncated; /* CS поднялся раньше 32 байт */
    uint8_t  last[32];
} spi_link_stat_t;

void spi_link_start(void);

/* Снимок счётчиков для печати. Читается без блокировки: для лога этого хватает. */
void spi_link_get_stat(spi_link_stat_t *out);
