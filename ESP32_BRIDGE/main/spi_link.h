/*
 * spi_link.h
 *
 * Ведомый SPI к прибору K57: посылка 512 байт раз в 2 мс, полный дуплекс.
 * Формат и все решения - docs/esp32-spi-protocol-RU.md. Сторона прибора -
 * INVERTOR_CCS/my_Files/wifi_link.c.
 *
 * Всё в посылке - 16-битные слова, по проводу старший байт первым:
 *
 *   слово 0     метка: 0xA55A от прибора, 0x5AA5 от нас
 *   слово 1     номер посылки
 *   слово 2     байт кадров дальше
 *   слово 3     прибор: сколько кадров не влезло с прошлой посылки
 *   слова 4...  кадры: номер (ID CAN), длина в байтах, данные
 *   слово 255   от нас к прибору: CRC-16/CCITT слов 0..254
 *
 * «Есть данные» опускается, когда транзакция заряжена: прибор без этого
 * обмен пропускает. Две транзакции в очереди - пока идёт одна, вторая уже
 * готова, и ножка между посылками не поднимается.
 */
#pragma once

#include <stdint.h>

#define SPI_LINK_BYTES 512

typedef struct {
    uint32_t packets;   /* посылок от прибора */
    uint32_t truncated; /* CS поднялся раньше 512 байт */
    uint32_t badMagic;  /* нет метки 0xA55A: сдвиг на бит или мусор */
    uint32_t badLayout; /* кадр вылез за конец посылки или длина не та */
    uint32_t seqGap;    /* номер посылки не подряд - прибор пропустил обмен */
    uint32_t f28Drop;   /* сумма слова 3: кадров, не влезших на приборе */

    uint32_t fr103;     /* кадров по номерам */
    uint32_t fr140;
    uint32_t fr1;
    uint32_t fr132;
    uint32_t frOther;
    uint32_t tickGap;   /* разрывы счётчика тактов в кадрах 103 */

    uint16_t lastFill;  /* байт кадров в последней посылке */
    uint16_t maxFill;
} spi_link_stat_t;

void spi_link_start(void);

/* Снимок счётчиков для печати. Читается без блокировки: для лога этого хватает. */
void spi_link_get_stat(spi_link_stat_t *out);
