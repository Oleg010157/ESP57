/*
 * web.h
 *
 * HTTP-сервер моста, порт 80. Сейчас на нём:
 *
 *   GET  /version   версия прошивки моста (JSON) - без пароля;
 *   POST /update    новая прошивка моста: тело запроса - файл
 *                   build/esp32_bridge.bin целиком. С паролем.
 *
 * Позже здесь же будет страница прибора для браузера.
 *
 * ПАРОЛЬ - HTTP Basic, пользователь k57, пароль CONFIG_K57_ADMIN_PASS из
 * sdkconfig.local; не задан - пароль точки доступа CONFIG_K57_AP_PASS.
 * Вводится в поле на странице; окна входа браузера нет (web_auth_ok).
 *
 * ОБНОВЛЕНИЕ. Прошивка пишется в свободное из двух мест под программу
 * (partitions.csv), загрузчик переключается на неё, мост перезапускается.
 * Новая прошивка сначала ПРОБНАЯ (CONFIG_BOOTLOADER_APP_ROLLBACK_ENABLE):
 * она должна сама подтвердить, что поднялась (web_confirm_if_pending из
 * main.c). Не подтвердила за 60 с - перезапуск, и загрузчик возвращает
 * прежнюю. Так неудачная прошивка не оставляет мост без связи.
 *
 * Пока идёт запись во флеш, обмен с прибором прерывается, как при сохранении
 * чёрного ящика (bbox.c): прибор видит мост неготовым и посылки пропускает.
 */
#pragma once

#include <stdbool.h>

void web_start(void);

/* Из главного цикла раз в секунду. Новая прошивка проработала 20 с - она
 * годная: отменить возврат к прежней. Для прошивки, которая уже признана,
 * ничего не делает. */
void web_confirm_if_pending(void);

/* Версия и что за раздел - для лога при старте. */
const char *web_version(void);

/* Страница прибора и её данные - web_page.c. */
#include "esp_http_server.h"
void web_page_register(httpd_handle_t srv);

/* Пароль запроса (Basic, k57:пароль). false - ответ 401 уже ушёл. */
bool web_auth_ok(httpd_req_t *req);

/* Идёт обновление самого моста - второе место под программу занято
 * (там же образ прошивки прибора, fwup.h). */
bool web_updating(void);
