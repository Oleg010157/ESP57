/*
 * fwup.h
 *
 * Прошивка прибора K57 через мост: страница или Motor_Control присылают
 * образ, мост кладёт его к себе во флеш и сам прошивает прибор по SPI.
 *
 * ПОЧЕМУ ТАК, А НЕ ПЕРЕСЫЛКОЙ С ПК. Прибор стирает свой флеш раньше, чем
 * получает новую прошивку, и между стиранием и пуском живёт только в ОЗУ.
 * Если в это время пропал WiFi, прибор встал бы без программы. Поэтому образ
 * сначала целиком приходит в мост и проверяется, и только потом мост зовёт
 * прибор в загрузчик - дальше всё идёт по проводам SPI, WiFi не участвует.
 *
 * Протокол с прибором - тот же, что у CAN-загрузчика с Motor_Control
 * (INVERTOR_CCS/my_Files/Bootloader/CAN_Bootloader_Protocol.md), кадры 0x33
 * и 0x32 едут в посылке SPI (там же, boot_spi.h). Вход - кадр
 * BOOT_SPI_ENTER: его ставит только мост, из сети его не прислать.
 *
 * ОБРАЗ - файл «K57F», его собирают из .out страница (page/index.html) и
 * Motor_Control (CAN/BridgeUpdate.cs). Всё младшим байтом вперёд:
 *
 *   0   'K57F'                      0x4637354B
 *   4   версия формата = 1, u16
 *   6   длина заголовка = 64, u16
 *   8   адрес входа _c_int00, слово прибора
 *   12  сегментов
 *   16  байт после заголовка
 *   20  время файла .out, UTC
 *   24  имя файла, 40 байт UTF-8, добито нулями
 *   64  сегменты: адрес (слово), длина (байт), данные
 *
 * Сегменты - ровно то, что ушло бы в шину: начало кратно 32 словам, длина -
 * 64 байтам, всё в BANK0..BANK3 (0x080000..0x0FFFFF). BANK4 с калибровками не
 * трогается никогда - и мост, и прибор проверяют это каждый сам.
 *
 * ГДЕ ХРАНИТСЯ. Во втором месте под программу моста (OTA): после
 * подтверждения новой прошивки моста оно свободно, и там 1,4 МБ - весь флеш
 * прибора (1 МБ) входит целиком. Следующее обновление моста образ сотрёт, и
 * это нормально: нужен он только на время прошивки.
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

#define FWUP_ID_TO_F28   0x33 /* кадры загрузчику - BOOT_CAN_RX_ID */
#define FWUP_ID_FROM_F28 0x32 /* кадры загрузчика - BOOT_CAN_TX_ID */

void fwup_init(void);

/* Из задачи SPI: каждый кадр прибора. */
void fwup_frame(uint16_t id, const uint8_t *data, uint8_t len);

/* Из задачи SPI, при сборке посылки: следующий кадр к загрузчику, если он
 * есть и влезает в room байт. Возвращает длину (кадр в data), иначе 0. */
int fwup_tx_next(uint8_t *data, int room);

/* Приём образа (HTTP). begin - NULL или причина отказа. */
const char *fwup_store_begin(uint32_t len, uint32_t utc);
bool        fwup_store_write(const void *data, uint32_t len);
const char *fwup_store_end(void); /* NULL - образ принят и проверен */

/* Начать прошивку прибора образом из моста. NULL - пошла, иначе причина. */
const char *fwup_start(void);

/* Остановить прошивку. До стирания прибор вернётся к прежней прошивке
 * (CMD_ABORT загрузчику), после - останется ждать в загрузчике новый образ.
 * NULL - принято, иначе причина. */
const char *fwup_stop(void);

/* Спросить у прибора версию (команда 333) - для страницы. */
void fwup_ask_version(void);

/* Мост занят прибором: принимает образ или прошивает. Обновлять сам мост в
 * это время нельзя - образ лежит в том же месте. */
bool fwup_busy(void);

typedef enum { FWUP_IDLE, FWUP_RUN, FWUP_OK, FWUP_FAIL } fwup_state_t;

/* Шаги прошивки - для времени по шагам (fwup_status_t.ph). */
enum {
    FWUP_PH_CHECK, /* образ в мосте и прибор: ключи, сеанс */
    FWUP_PH_ENTER, /* вход в загрузчик и связь с ним */
    FWUP_PH_ERASE,
    FWUP_PH_WRITE,
    FWUP_PH_START, /* сверка суммы и пуск */
    FWUP_PH_ALIVE, /* до ответа новой прошивки на 333 */
    FWUP_PHASES
};

typedef struct {
    /* образ в мосте */
    bool     img;          /* есть и цел */
    char     name[41];
    uint32_t fileTime;     /* время .out */
    uint32_t upTime;       /* когда прислан */
    uint32_t bytes;        /* данных для прибора, байт */
    uint32_t segs;
    uint32_t entry;
    /* прошивка */
    fwup_state_t state;
    int      pct;
    int      attempt;
    uint32_t elapsed;      /* мс с начала */
    char     msg[112];
    /* время последней прошивки, мс: приём образа, шаги удачной попытки и вся
     * прошивка от «Прошить» до ответа (с неудачными попытками, если были) */
    uint32_t upMs;
    uint32_t ph[FWUP_PHASES];
    uint32_t totalMs;
    /* прибор */
    bool     inBoot;       /* загрузчик прибора слышен (кадры 0x32 за 2 с) */
    char     devId[33];    /* что прибор ответил на 333 */
    char     devBuild[33]; /* дата и время его сборки */
} fwup_status_t;

void fwup_status(fwup_status_t *out);
