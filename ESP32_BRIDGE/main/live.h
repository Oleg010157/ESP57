/*
 * live.h
 *
 * Живое состояние прибора для страницы в браузере (web.c): последний
 * медленный кадр 140, лампа ошибок и таблица ошибок, собранная из кадров
 * 132. Пишет только задача SPI, читают обработчики HTTP.
 *
 * ЧЕЙ СЕАНС. Кадр 140 прибор шлёт в сеансе Motor_Control (команда 2) - или пока
 * идёт «только смотреть» (команда 344, INVERTOR_CCS/KSP/MBOX28.c). Сеанс
 * Motor_Control для страницы не годится: «Подключить» закрывает ключи, и прибор,
 * работающий в сети сам, встал бы оттого, что кто-то открыл страницу. Поэтому:
 *
 *   сеанс Motor_Control открыт        - страница только смотрит то, что идёт
 *                                      по его сеансу, команд мост не шлёт;
 *   сеанса нет, страница открыта      - мост раз в секунду шлёт 344: кадр
 *                                      140, лампа, раз в три секунды - список
 *                                      ошибок. Ключи и уставки не трогаются.
 *
 * «Сеанса нет» - и когда Motor_Control закрыт, и когда он подключён к мосту,
 * но в нём нажато «Отключить» (12.11.2026). Узнаём это у самого прибора: бит 0
 * слова 2 кадра 140 - sbit.connect. Кадров нет дольше 1,5 с - сеанса тоже нет.
 *
 * «Страница открыта» - браузер спрашивал /api/state меньше 10 с назад.
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

#define LIVE_ERR_CODES 100 /* ERR_BUFF_SIZE прибора */

typedef struct {
    uint16_t w[32];     /* кадр 140 как есть */
    uint32_t age;       /* мс с последнего кадра 140; UINT32_MAX - не было */
    uint16_t lamp;      /* лампа ошибок: секунд, сколько ещё гореть */
    uint32_t lampAge;   /* мс с последнего ответа о лампе */
    uint32_t errAge;    /* мс с последнего полного списка ошибок */
    bool     pult;      /* Motor_Control подключён к мосту по сети */
    bool     session;   /* у Motor_Control открыт сеанс с прибором («Подключить») */
    bool     watching;  /* мост сам держит «только смотреть» */
} live_state_t;

/* Из задачи SPI, на каждый кадр прибора. */
void live_frame(uint16_t id, const uint8_t *data, uint8_t len);

/* Из главного цикла, раз в секунду: держит «только смотреть». */
void live_tick1s(void);

/* Из HTTP: браузер спросил состояние - страница открыта. */
void live_touch(void);

void live_get(live_state_t *out);

/* Таблица ошибок: слово ErrBuff и время (UTC) последнего раза, по коду.
 * Возвращает false, если полного списка ещё не было. */
bool live_errors(uint16_t word[LIVE_ERR_CODES], uint32_t utc[LIVE_ERR_CODES]);
