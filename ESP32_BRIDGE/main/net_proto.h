/*
 * net_proto.h
 *
 * Обмен моста с программой на ПК. Полностью - docs/esp32-spi-protocol-RU.md,
 * раздел «Сеть».
 *
 * Мост переносит кадры CAN как есть, поэтому и в сети единица обмена - кадр:
 *
 *   байт 0    0xA5 - метка записи: по ней TCP-поток находит начало кадра,
 *             если синхронизация потеряна
 *   байт 1    длина данных, байт (0..64)
 *   байт 2-3  ID кадра CAN, младший байт первым
 *   байт 4... данные - ровно DATA кадра CAN FD, в том же порядке байт
 *
 * TCP 5520 - команды (ПК -> мост, ID 2), ACK и ошибки (мост -> ПК, ID 1, 132):
 *            надёжно и по порядку. Клиент один.
 * UDP 5521 - телеметрия 103 и 140 (мост -> ПК). Датаграмма:
 *
 *   байт 0-3  "K57F"
 *   байт 4-5  номер датаграммы, младший байт первым - по разрывам видны потери
 *   байт 6-7  кадров, не влезших в посылку на приборе, с прошлой датаграммы
 *   байт 8... кадры, как выше
 *
 * Чтобы телеметрия пошла, ПК раз в секунду шлёт на UDP 5521 датаграмму
 * "K57U" со своего UDP-сокета: адрес и порт мост берёт из неё. Так обратный
 * поток становится ответом на исходящий, и брандмауэр Windows его пропускает
 * без прав администратора - разобрано в ESP_INV, net_tele.c.
 */
#pragma once

#define K57_TCP_PORT  5520
#define K57_UDP_PORT  5521
#define K57_MDNS_HOST "k57" /* k57.local */

#define K57_REC_SYNC  0xA5
#define K57_REC_HDR   4
#define K57_DATA_MAX  64

/* Служебная запись моста, не кадр прибора: ID вне тех, что знает прибор и
 * пульт. Мост шлёт её по TCP сразу после подключения. Данные - текст ASCII:
 *     "STA <имя сети>"   мост вошёл в общую сеть
 *     "AP <имя сети>"    мост поднял свою точку доступа
 * Пульт показывает имя сети в заголовке рядом с адресом. */
#define K57_INFO_ID   0x7F0

#define K57_UDP_MAGIC "K57F"
#define K57_UDP_HELLO "K57U"
#define K57_UDP_HDR   8
