/*
 * bstore.h
 *
 * Второе хранилище прибора в мосте: длинный журнал событий и копия настройки.
 * Главное хранилище остаётся в приборе (EEPROM и флеш F28) - прибор работает
 * и без моста. Сторона прибора - INVERTOR_CCS/my_Files/bridge_store.c.
 *
 * ЖУРНАЛ - во флеше, последние 64 кБ раздела bbox (чёрный ящик занимает
 * первые 960 кБ): 16 секторов по 256 записей. Каждое новое событие прибора -
 * строка: номер, UTC, код, сессия. Один код - не чаще раза в минуту: повторы
 * внутри минуты считаются и через минуту ложатся одной строкой «ещё N раз».
 * Заполнился - пишет поверх самого старого сектора. Около 3800 строк.
 *
 * КОПИЯ НАСТРОЙКИ - в NVS. Прибор присылает запись CalibBlob при включении,
 * после каждого сохранения и по команде 341 (мост даёт её сам, поднявшись).
 * Пустую или чужую мост не берёт - прежняя копия остаётся. Пишется, только
 * если изменилась.
 *
 * Пульт читает журнал и копию по TCP. Восстанавливает пульт сам, командами
 * прибору 342/343: мост в этом не участвует.
 *
 * Формат - docs/esp32-spi-protocol-RU.md, раздел «Журнал и копия настройки».
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

/* прибор -> мост */
#define BST_ID_EVENT     0x7D1 /* код, UTC мл., UTC ст., сессия */
#define BST_ID_CAL_HDR   0x7D2 /* копия: заголовок, 12 слов - идёт и пульту */
#define BST_ID_CAL_DATA  0x7D3 /* копия: смещение и до 30 слов - идёт и пульту */
/* пульт -> мост и обратно */
#define BST_ID_JREAD     0x7D8 /* пульт: журнал целиком */
#define BST_ID_JRECS     0x7D9 /* мост: до трёх строк журнала по 16 байт */
#define BST_ID_JEND      0x7DA /* мост: конец журнала - строк, ёмкость, потеряно */
#define BST_ID_JCLEAR    0x7DB /* пульт: стереть журнал; ответ - JEND */
#define BST_ID_COPY      0x7DC /* пульт: копия настройки */
#define BST_ID_COPY_HDR  0x7DD /* мост: заголовок копии, как BST_ID_CAL_HDR, и UTC приёма */
#define BST_ID_COPY_DATA 0x7DE /* мост: как BST_ID_CAL_DATA */
#define BST_ID_COPY_END  0x7DF /* мост: 1 - копия была, 0 - копии нет */

#define BST_IS_OWN_ID(id) (((id) & 0xFFF0u) == 0x7D0u)
/* Что из этого мост отдаёт пульту как есть: живая запись прибора, чтобы
 * пульт мог сравнить её с копией. */
#define BST_TO_PC(id)     ((id) == BST_ID_CAL_HDR || (id) == BST_ID_CAL_DATA)

typedef struct {
    uint32_t events;    /* событий принято от прибора */
    uint32_t written;   /* строк записано во флеш */
    uint32_t folded;    /* повторов свёрнуто в счётчик */
    uint32_t lost;      /* очередь была полна */
    uint32_t rows;      /* строк в журнале сейчас */
    bool     haveCopy;  /* копия настройки есть */
    uint32_t copies;    /* копий принято от прибора */
    uint32_t copyBad;   /* копий отброшено: не сошлась сумма или длина */
    bool     noFlash;
} bstore_stat_t;

/* После net_wifi_start (NVS уже поднят) и до bbox_start: свою память
 * берёт раньше кольца чёрного ящика. */
void bstore_start(void);

/* Из задачи SPI, на каждый кадр прибора. Ничего не ждёт. */
void bstore_frame(uint16_t id, const uint8_t *data, uint8_t len);

/* Запрос пульта - из задачи TCP. */
void bstore_request(uint16_t id, const uint8_t *data, uint8_t len);

void bstore_get_stat(bstore_stat_t *out);
