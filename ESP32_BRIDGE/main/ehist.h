/*
 * ehist.h
 *
 * Почасовая история счётчиков энергии прибора - для графиков страницы
 * (вкладка «Энергия»: сутки по часам, месяц по дням, год по месяцам). С
 * 13.11.2026.
 *
 * Считает энергию сам прибор (INVERTOR_CCS/my_Files/energy.h), мост только
 * запоминает показания «всего» - раз в час, в первую же минуту часа: час (UTC
 * / 3600), отдано и принято, Вт·ч. Энергия за час - разность соседних
 * записей. Мост был выключен или не знал времени - несколько часов сольются
 * в один промежуток, но ничего не пропадёт: «всего» копит прибор.
 *
 * Место - бывшее седьмое место чёрного ящика, 0xC0000..0xDFFFF раздела bbox
 * (bbox.c): 32 сектора, в каждом метка 'K57E' и 340 записей по 12 байт - около
 * 450 суток. По кругу: дойдя до конца, стирает самый старый сектор.
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

typedef struct {
    uint32_t hour; /* UTC / 3600 */
    uint32_t out;  /* отдано всего, Вт·ч - на начало часа */
    uint32_t in;   /* принято всего, Вт·ч */
} ehist_rec_t;

/* Один раз при старте: найти конец истории. Старое содержимое места (запись
 * чёрного ящика) стирается. */
void ehist_init(void);

/* Показания счётчиков в час hour. Пишется одна запись на час - первая. */
void ehist_add(uint32_t hour, uint32_t out, uint32_t in);

/* Все записи с часом в [from, to] - в порядке записи (по кругу), cb на каждую. */
void ehist_walk(uint32_t from, uint32_t to, void (*cb)(const ehist_rec_t *r, void *ctx), void *ctx);
