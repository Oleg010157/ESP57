/*=================================================================================
 Структура управления

 в структуре собранны параметры управления от PC общие для обоих двигателей
 ===================================================================================*/
typedef struct
{

    uint16_t speedRef;		// заданная скорость (rpm) ротора или поля,  об/мин
    uint16_t speedRef_KVU; // заданная скорость (rpm) ротора или поля,  от КВУ , об/мин
    int voltMax;		// Напряжение включения тормозного резистора
    int voltMin;		// Напряжение выключения тормозного резистора
    int currentMax;	// Максимальный ток срабатывания защиты, при котором выключаются IGBT
    int UdcMax;     // Максимальное  напряжение Udc, при котором выключаются IGBT
    float ipVq;
    float ipVd;
    float epsi;           // заданный epsi в радианнах
    long ramp_step; // ограничение скорости изменения магн. поля статора в об/мин * 100 000
    float korUDC;
    //				float   k_piUmax;
    float kIqRPM;

} REFs;

typedef struct
{
    int vRtor_on;		// напряжение Udc Вольт включения тормозного резистора
    int vRtor_off;		// напряжение Udc Вольт выключения тормозного резистора
    int Rtor_pwm;			// задаёт скважность включения резистора

} RTORMOZ;

/*==============================================================================
 Структура Данных для заданния различных режимов
 =================================================================================*/
typedef struct
{
    float Udc_stab;			// напряжение для стабилизации
    float U_lim_Low;
    float U_lim_High;
    float s_prop;		// ограничение по скольжению (пропорциональный коэф.)
    float s_limit;			// ограничение по скольжению (постоянный коэф.)
    float s_full;// полное скольжение для торможения (учитывая пропорциональный регулятор)

    float Kuf;				// Мультипликативный коэф. для U/f генератора
    int ref_temp;// Добавка к  укставке оборотам двигателя в режиме стабилизации RPM вала спарки 0.1 об/мин .
    float s_gen;// коеф сдвига нагрузочного скольжения REF.sAbs для генератора
    float V_koef;		// Мультипликативный коэф. для регулятора по скольжению
    float step1;				// аддитивный шаг для регулятора по напряжению
    float step2;				// аддитивный шаг для регулятора по скольжению
    float Prev_Vref;// временная переменная для сохранения Gain'a перед торможением
} MODEs;




