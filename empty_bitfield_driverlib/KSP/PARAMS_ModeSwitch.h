/* =================================================================================
      	 	 	 	 	 Ключи для режима имитации
===================================================================================*/
typedef struct
{
    uint16_t Udci : 1;            // 31:30
    uint16_t Ia1 : 1;             // 30:29
    uint16_t Ib1 : 1;             // 29:28
    uint16_t Ic1 : 1;             // 28:27
    uint16_t Ia2 : 1;             // 27:26
    uint16_t Ib2 : 1;             // 26:25
    uint16_t Ic2 : 1;             // 25:24
    uint16_t CALIBR : 1;          // 24:23
    uint16_t Error : 1;           // 23:22
    uint16_t transistor_imit : 1; // 22:21		ключ включения режима IGBT on/off
    uint16_t Udci2 : 1;           // 21:20
    uint16_t adc_transmitt : 1;   // 20:19

} MODE_SW;

