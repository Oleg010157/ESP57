/*-------------------------- Сруктура битовая для характеристики ошибок по оптике ----------------------- */
typedef struct
{
    uint16_t Err1 : 1;  // T1
    uint16_t Err2 : 1;  // T2
    uint16_t Err3 : 1;  // T3
    uint16_t Err4 : 1;  // T4
    uint16_t Err5 : 1;  // T5
    uint16_t Err6 : 1;  // T6
    uint16_t Err7 : 1;  // TR
    uint16_t Q_T16 : 1; // выход RS тригера захвата ошибки по оптике Т1-Т6
    uint16_t Q_TR : 1;  // выход RS тригера захвата ошибки по оптике тормозного резистора

    uint16_t Err_sum;

} OPTIC_ERRs;



typedef struct
{
    uint16_t rpm_Mode : 4;
    uint16_t u1_Mode : 4;
    uint16_t u2_Mode : 4;
} mode;

typedef union
{
    mode   bits;
    uint16_t all;
} SharpMode;

//-----------------------------------------------------------------
typedef struct
{
    uint16_t connect : 1;         //0 кнопка "Подключить/Отключить" -> 1/0
    uint16_t Reverse : 1;         //1 глобальная кнопка "Reverse" -> 1/0
    uint16_t ResolverInverse : 1; //2 инвертирует сигнал Резолвера
    uint16_t pusk : 1;            // 3 устанавливается по команде "Пуск", сбрасывается по команде
    uint16_t motfast : 1;         //4 бит управляет выбором мотора для записи в быстрый кадр 0- мотор1, 1- мотор2
    uint16_t motK60 : 1;          //5 бит управляет выбором мотора для записи в медленный  кадр
} Stend_bit;

typedef union
{
    Stend_bit bit;
    uint16_t    all;
} STEND_bit;

//-----------------------------------------------------------------------------------------------------------------
typedef struct
{
    uint16_t rgPause : 1; // =1 для организации паузы перед перемещением вектора напряжения, =0 в момент когда Im < 1 Amp
    uint16_t ImaxOff : 1;
    uint16_t dImaxOff : 1;
    uint16_t UmaxOff : 1;
    uint16_t Lkadr : 1;
    uint16_t Lready : 1;
    uint16_t LdReady : 1;
    uint16_t Rready : 1;
    uint16_t Um1 : 1;
} L_bits;

typedef union
{
    L_bits bits;
    uint16_t all;
} L_flag;

typedef struct
{
    uint16_t rg_start; // =0 cancel test, =1 start Ain1, =2 start Ain2
    float U_step;   // step , Вольт
    uint16_t pause;    // пауза между изменением напряжения в тиках 500 мкс
    uint16_t U_max;    // максимальное напряжение Urms для теста, Вольт
    float I_max;    // максимальный ток Im  для теста, Ампер
    float dI_max;   // максимальное приращение тока Im  для теста, Ампер

    float rg_step; // шаг изменения угла вектора напряжения, град.

    uint16_t cntr;   // счётчик длительности паузы
    float Imt;    // прошлое значение Im в предыдущем тике
    float Im0;    // значение Im в момент изменения напряжения
    float L;      // измеренная индуктивность
    float Ldown;  // измеренная индуктивность
    float R;      // измеренное сопротивление
    uint16_t Lcnt;   // момент измерения индуктивности
    uint16_t Rcnt;   // момент измерения сопротивления
    L_flag flag;   // флаги состояний
    float Upause; // напряжение перед входом в паузу

    // 15.12.2016
    uint16_t Ucnt; // номер площадки напряжения ->  0,1,2

    float Um1, Im1; // установившиеся напряжение и ток  первой площадки
                     //       float Ur2,Ir2;   // установившиеся напряжение и ток  второй площадки

} L_TEST;


