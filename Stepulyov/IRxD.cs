namespace ICDIBasic
{
    /// <summary>
    /// Приёмник собранной записи осциллографа.
    ///
    /// Заведён 06.09.2026 для K56. Раньше веер в CanaAsync.F2_RxData раздавал
    /// запись спискам List&lt;RxDataFrm&gt;, то есть одной конкретной форме с
    /// DataGridView внутри. Новой форме осциллографа наследоваться от неё
    /// незачем - ей нужен только сам метод, - поэтому списки переведены на
    /// этот интерфейс. RxDataFrm ему уже удовлетворяла: оба члена у неё были.
    ///
    /// ВАЖНО про массив в RxD. Он приходит по ссылке и ЖИВЁТ ТОЛЬКО ВНУТРИ
    /// ВЫЗОВА: сразу после веера CanaAsync переставляет в нём байты местами,
    /// готовя кадр к записи в файл. Invoke синхронный, поэтому до этого места
    /// дело доходит уже после возврата из RxD - но если сохранить ссылку,
    /// содержимое перевернётся под руками. Значения нужно КОПИРОВАТЬ.
    /// </summary>
    public interface IRxD
    {
        /// <summary>Имя формы: по нему ищут уже открытую.</summary>
        string Name { get; }

        /// <summary>
        /// Очередная собранная запись, слова кадра в том же порядке, в каком
        /// их складывает SplKadr. Зовётся В ПОТОКЕ UI и на КАЖДУЮ запись - при
        /// такте 5 кГц это пять тысяч вызовов в секунду. Рисовать здесь
        /// нельзя: поток приёма ждёт возврата, и записи начнут теряться.
        /// Дело этого метода - положить значения в буфер и выйти.
        /// </summary>
        void RxD(ushort[] d);
    }
}
