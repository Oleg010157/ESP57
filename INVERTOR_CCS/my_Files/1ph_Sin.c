void adjustPhaze(void)
{
    if (GpioDataRegs.GPASET.bit.GPIO26)
    {
        GpioDataRegs.GPBSET.bit.GPIO32 = 1;
        if (dacb > 2048)
            sine0 = sine0 + zstep;
        else
            sine0 = sine0 - zstep;
        Cmpss3Regs.COMPSTSCLR.bit.HLATCHCLR = 1;
    }
    else
    {
        GpioDataRegs.GPBCLEAR.bit.GPIO32    = 1;
        Cmpss3Regs.COMPSTSCLR.bit.HLATCHCLR = 1;
        if (dacb < 2048)
            sine0 = sine0 + zstep;
        else
            sine0 = sine0 - zstep;
    }
    // DEVICE_DELAY_US(50);
}
