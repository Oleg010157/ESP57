//                              Раскладка - у самой отправки, ниже по файлу.
//
// Формат обоих менять можно только тремя местами разом: прошивка, разбор в
// Motor_Control (Oleg/Kadr60.cs, ProcessFrame103) и настройки каналов Wscope
// (bin/Wscope/F3_convertor.ini). Приёмная сторона читает по НОМЕРУ СЛОВА,
// имён в кадре нет.
//
// ЧЕТВЁРТОЕ СЛОВО - sineTick, и это не украшение. Send_mbox_FD молча пропускает
// кадр, если буфер занят передачей предыдущего, а пропуск в ленте неотличим
// от настоящей паузы в сигнале: Wscope нарисует сжатый по времени участок и
// это будет выглядеть как реальная динамика. По разрывам sineTick пропуск
