           // оно в этом канале честно проявится.
           float nInv = (gt.n > 0.1f) ? (1.0f / gt.n) : 0.0f;

           f[0] = (int16_t)(10000.0f * phaseErr); // 1e-4
           f[1] = (int16_t)(10.0f * gt.uGrid);   // 0.1 В
           f[2] = (int16_t)(100.0f * gt.iref);   // 0.01 А
           f[3] = (int16_t)(100.0f * iSec_amp); // 0.01 А
           f[4] = (int16_t)(100.0f * iPri_amp); // 0.01 А
           f[5] = (int16_t)(10000.0f * gt.m);    // 1e-4
           f[6] = (int16_t)(10000.0f * (1.0f - (float)cmpaA / (float)tbprd));
           // Напряжение звена - ИЗМЕРЕННОЕ, с датчика (канал uBat, A4).
           //
           // Здесь стояло gt.Udc, и это была ошибка: gt.Udc - не измерение, а
           // то, ЧЕМ КОНТУР ДЕЛИТ, и при UdcSrc = 0 туда подставляется
           // константа UdcFixed. В ленту ехала бы прямая линия вместо сигнала.
