void dacDbg_scale_default(void)
{
    static uint16_t last = 0xFFFFU; // заведомо не номер источника: первая же
                                    // команда обязана поставить свой масштаб

    if (dacDbgSrc == last)
        return;
    last = dacDbgSrc;

    if (dacDbgSrc < (sizeof(kDacDbgDef) / sizeof(kDacDbgDef[0])))
        kDacDbg = kDacDbgDef[dacDbgSrc];
}

