/* sine_invertor1 УДАЛЁН 17.08.2026.
 *
 * Это был метод, где в каждой полуволне модулирует только одно плечо, а второе
 * стоит с постоянно открытым нижним ключом. Вдвое меньше переключений - и
 * фатальный для трансформатора порок: КАЖДАЯ ПОЛУВОЛНА ФОРМИРУЕТСЯ СВОИМ
 * ЖЕЛЕЗОМ. Положительная - плечом A, отрицательная - плечом B. Любое различие
 * между плечами (задержки драйверов, время выключения ключей, Vce(sat) нижнего
 * ключа, тепловая точка) попадает целиком в одну полуволну и не попадает
 * в другую, то есть превращается в постоянную составляющую напряжения.
 * Трансформатор её интегрирует в поток и уходит в насыщение.
 *
 * Порядок величины: мёртвое время 2 мкс на периоде ШИМ 200 мкс при Udc = 48 В
 * даёт вольт-секундную ошибку 0.48 В. Расхождение плеч всего в 10 % от неё -
 * это 48 мВ постоянной составляющей на первичке, 336 мВ на вторичке.
 *
 * Вторая причина: знак U_AB жёстко привязан к знаку опорной синусоиды, мост
 * не может выдать напряжение против опоры. Замкнутому контуру тока это нужно
 * регулярно, и без этого он упирается в ОДНОСТОРОННЕЕ ограничение - а это само
 * по себе машина по производству постоянной составляющей.
 *
 * Разбор целиком - my_Files/grid_tie.txt, раздел 9. Код - в истории git.
 */

#pragma CODE_SECTION(sine_invertor2, ".TI.ramfunc");

void sine_invertor2(struct sine *s)
{
    /* В этом методе в режиме ШИМ работают все четыре ключа.
     * ключи фазы А (EPWM1) модулируются скважностью = duty, 
     * а ключи фазы В (EPWM6) модулируются скважностью = (1-duty)
     * Вычисление duty происходит в прерывании которое запускается при достижении
     * счётчиком значения: TBCNT =  pwm_period, а загрузка нового значения скважности в 
     * компаратор CMPA происходит позже когда TBCNT = 0.
    */

    // вычисление нового значения скважности для ШИМ.
    // Скважность нормируется в диапазоне от 0 до 1 и умножается на коэффициент амплитуды amp,
    // который тоже нормируется от 0 до 1 -> amp = Uab/Vin;  где Uab - выходное напряжение, а
    // Vin - входное напряжение от АКБ

    // нормируем скважность в диапазоне от 0 до 1
    duty           = (0.5f * sinf(s->angle + s->offset) + 0.5f);
    float tbperiod = s->gain / 2048.0f * s->pwm_period;

    // Оба компаратора считаются НЕЗАВИСИМО из float.
    //
    // Раньше было cmpaB = tbperiod - EPwm1Regs.CMPA, то есть вычитание из уже
    // УСЕЧЁННОГО регистра. Присваивание float->uint16 усекает к нулю, и такая
    // разность двух усечений даёт односторонний сдвиг в полкода:
    //   cmpaB - cmpaA = tbperiod*(2*duty-1) + 2*frac - 0.5,  E[2*frac-0.5] = +0.5
    // При TBPRD = 7500 это 6.7e-5 от Udc: 3 мВ на первичке, ~22 мВ на вторичке.
    // Для активной нагрузки пренебрежимо, а трансформатор интегрирует это
    // в поток. При независимом расчёте смещения обоих усечений одинаковы
    // и в разности сокращаются.
    //
    // Порядок (1-duty) для плеча A и duty для плеча B, а не наоборот:
    // доля открытого состояния плеча = 1 - CMPA/TBPRD, поэтому
    //   U_AB = (cmpaB - cmpaA)/TBPRD * Udc = tbperiod/TBPRD * sin(angle) * Udc
    // то есть ПОЛОЖИТЕЛЬНЫЙ синус даёт положительное напряжение - как в
    // прежнем sine_invertor1. В старой редакции знак был обратным, и переход
    // на этот метод развернул бы мост на 180 градусов относительно dacb,
    // к которому привязан контур фазы.
    // Поправка постоянной составляющей. Сдвигает компараторы НАВСТРЕЧУ друг
    // другу, ровно на столько, чтобы к напряжению моста добавилось mDC*Udc:
    // U_AB = (cmpaB - cmpaA)/TBPRD * Udc, значит каждому по mDC*TBPRD/2.
    //
    // Добавлено 23.09.2026. До того контур подавления в острове не работал
    // вовсе - и не считался, и применять его было некуда. Трансформатору же
    // безразлично, каким режимом ему наливают вольт-секунды; разбор -
    // grid_tie.txt, 3.1.
    //
    // Ограничение обязательно: при mDC на потолке сдвиг равен 0.01*TBPRD,
    // то есть 75 тактов, и у края синусоиды tbperiod*(1-duty) уже нулевое.
    // Без клампа разность ушла бы в минус, а присваивание uint16 превратило
    // бы её в шестьдесят пять тысяч - полностью открытое плечо.
    float dc = 0.5f * mDC * (float)s->pwm_period;

    float ca = tbperiod * (1.0f - duty) - dc;
    float cb = tbperiod * duty + dc;
    float top = (float)s->pwm_period;

    ca = (ca < 0.0f) ? 0.0f : ((ca > top) ? top : ca);
    cb = (cb < 0.0f) ? 0.0f : ((cb > top) ? top : cb);

    cmpaA = (uint16_t)ca; // ШИМ для верхнего ключа фазы A
    cmpaB = (uint16_t)cb; // ШИМ для верхнего ключа фазы B

    // DINT/EINT вокруг записи убраны: оба регистра теневые и загружаются
    // одновременно по TBCTR = 0, так что пара атомарна относительно ШИМ сама
    // по себе. А EINT посреди обработчика открывал окно вложенных прерываний.
    EPwm1Regs.CMPA.bit.CMPA = cmpaA;
    EPwm2Regs.CMPA.bit.CMPA = cmpaB;

    // вычисление нового угла синусоиды и ограничение в диапазоне от -PI до PI
    s->angle = asut(s->angle + s->step);
}

