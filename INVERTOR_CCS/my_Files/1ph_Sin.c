    if (!sim.on)
        xfmr_currents_from_adc();

    // Измерения тракта (uGrid, Udc) и такт модели - до такта управления и в
    // обоих режимах моста.
    //
    // Порядок не переставлять. Модель обязана отработать тот индекс модуляции,
    // что реально стоял в компараторах последний период; посчитай её после
    // контура - и она окажется на такт быстрее реальности, показав
    // устойчивость, которой на железе не будет. А ЭДС сети ей нужна текущего
    // такта, отсюда и grid_tie_measure() впереди. Разбор - plant_sim.txt.
    //
    // Когда модель выключена (sim.on = 0), plant_sim_step() выходит сразу и
    // токи остаются теми, что прочитаны с АЦП строкой выше.
