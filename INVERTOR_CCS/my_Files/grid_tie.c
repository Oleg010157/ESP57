// dbg Команда пуска/останова из окна Watch. Смысл и коды - в grid_tie.h.
volatile uint16_t gtCmd = 0;

//---------------------------------------------------------------------------
// Трассировка формы сигналов. Объявления и смысл - в grid_tie.h,
// как этим пользоваться - grid_tie.txt, раздел 6.1.
//
// gtTrcRun = 2 - однократный снимок: буфер заполняется один раз и запись
// встаёт сама. Так ловится переходный процесс - поставил 2 одновременно
// с возмущением и получил ровно два периода вокруг него, а не бесконечную
// ленту, в которой момент возмущения уже затёрт.
//---------------------------------------------------------------------------
// Сами буферы - в RAMGS1. В .bss им места нет: он привязан к ОДНОМУ блоку
// RAMLS5 (0x800 слов), и четыре массива по 200 float (1600 слов) кладут
// линковку намертво. RAMGS1 - 0x2000 слов и пуст; приём в проекте уже
// применяется, см. ErrHistory в KSP/Errors.c.
#pragma DATA_SECTION(gtTrcIref, "ramgs1");
#pragma DATA_SECTION(gtTrcIb, "ramgs1");
#pragma DATA_SECTION(gtTrcIa, "ramgs1");
#pragma DATA_SECTION(gtTrcM, "ramgs1");

uint16_t gtTrcRun = 1;
uint16_t gtTrcIdx = 0;
float    gtTrcIref[GT_TRC_LEN];
float    gtTrcIb[GT_TRC_LEN];
float    gtTrcIa[GT_TRC_LEN];
float    gtTrcM[GT_TRC_LEN];

// TBCLK1 = 150 МГц / 2 (HSPCLKDIV=2 по сбросу) = 75 МГц, режим UP_DOWN даёт
// 2*TBPRD тактов на период. Отсюда Ts = TBPRD / 37.5e6.
#define TB1_TICKS_PER_SECOND_HALF 37.5e6f

//---------------------------------------------------------------------------
// Начальные значения.
//
// Все коэффициенты - float в структуре gt, чтобы крутить их в отладчике
// на живой цели, не пересобирая проект.
//
// Kp = 2*PI*f_bw*L. Значение f_bw ~ 300 Гц осталось от прежней схемы, когда
// такт управления сидел на прерывании EPWM1 и полная задержка контура была
// около 1.5 такта. Теперь обработчик висит на ADCB INT1 и задержка равна
// 0.5 такта (одна теневая загрузка CMPA), то есть на 300 Гц освободилось
// порядка 21 градуса фазового запаздывания. Потолок полосы от этого вырос,
// но НАСКОЛЬКО - надо мерить на железе, а не назначать: Ts = 200 мкс и шаг
// резонатора никуда не делись. Пока Kp оставлен прежним.
//
// Ki = Kp*w_r, w_r ~ 2*PI*20 - нулевая ошибка на 50 Гц примерно за 50 мс.
//---------------------------------------------------------------------------
void grid_tie_init(void)
{
    gt.State       = GT_OFF;
    gt.fault       = 0;
    gt.faultNew    = 0;
    gt.shutdownReq = 0;
    gt.syncCnt     = 0;
    gt.syncNeed    = 25; // 25 периодов сети = 0.5 с
    gt.startDelay  = 0;
    gt.acContactor = 0;
    gt.gridEn      = 0; // разрешение и запрос приходят из GUI, своего мнения
    gt.connReq     = 0; // о выходе в сеть прошивка при старте не имеет

    gt.IsetRef  = 0.0f;
    gt.Iset     = 0.0f;
    gt.IsetSlew = 0.1f; // А за период сети: с нуля до 5 А за секунду
    gt.Iq       = 0.0f;
    gt.UrefRms  = 220.0f;

    gt.u220Zero = 2048.0f; // до первого захвата; дальше - середина вилки
    gt.kU220    = 0.152f;  // В/код: 311 В пика на 2048 кодов. Уточнить при тарировке
    gt.n     = 7.0f;   // Uвтор/Uперв
    gt.iSign = 1.0f;

    gt.UdcSrc   = 0;     // на стенде АКБ нет - берём константу
    gt.UdcFixed = 48.0f;
    gt.Udc      = 48.0f;

    gt.pr.Kp   = 15.0f;   // = 2*PI*300*0.008
    gt.pr.Ki   = 1900.0f; // = Kp * 2*PI*20
    gt.pr.KiTs = 0.0f;    // считается в grid_tie_onGridZero()
    gt.pr.leak = 0.002f;
    gt.pr.step = 0.0f;
    gt.pr.x1   = 0.0f;
    gt.pr.x2   = 0.0f;
    gt.pr.xMax = 100.0f; // В на вторичке: падение на рассеянии много меньше
    gt.pr.out  = 0.0f;

    gt.mMax = 0.95f;
    gt.m    = 0.0f;

    // Контур подавления постоянки считает CLA, здесь только его параметры
    // и начальное состояние. Все четыре величины лежат в message RAM, а не
    // в gt, - разбор в cla_shared.h.
    mDC        = 0.0f;
    kDC        = 0.0005f; // установление около секунды
    mDCmax     = 0.02f;
    dcAllow    = 0;
    dcResetReq = 0;
    dcSatCnt   = 0;

    // 50 окон - это секунда при 50 Гц. Порог взят с запасом НАД предсказанным
    // звоном: по 3.1.6 петля с двумя интеграторами может колебаться около 1 Гц,
    // и на гребне такого колебания поправка законно простоит в упоре доли
    // секунды. Порог в полсекунды кричал бы на эту самую динамику.
    // Уточнить по первому прогону с железом, когда звон будет измерен.
    dcSatLimit = 50;

    gt.ImaxPri   = 100.0f; // уточнить по датчику первички
    gt.ImaxSec   = 25.0f;  // 3 кВт -> 19.3 А пика, запас 30 %
    gt.UdcMin    = 20.0f;
    gt.UdcMax    = 65.0f;
    gt.freqMin   = 47.0f;
    gt.freqMax   = 53.0f;
    gt.ampMin    = 1200.0f;
    gt.ampMax    = 2000.0f;
    gt.phaseOk   = 0.10f;
    gt.satCount  = 0;
    gt.satLimit  = 10; // из 100 тактов периода
    gt.satLast   = 0;
    gt.syncBad   = 0;
    gt.noGrid    = 0;
    gt.noGridMax = 150; // 1.5 периода сети

    gt.Ts     = 200e-6f;
    gt.refSrc = 0; // стенд: опора - daca

    grid_tie_apply_uref();
}

void grid_tie_apply_uref(void)
{
    float udc = (gt.Udc > 1.0f) ? gt.Udc : ((gt.UdcFixed > 1.0f) ? gt.UdcFixed : 48.0f);
    float n   = (gt.n > 0.1f) ? gt.n : 7.0f;
    float uref = (gt.UrefRms < 0.0f) ? 0.0f : gt.UrefRms;
    float peakPri = uref * 1.41421356f / n;
    float g = 2048.0f * peakPri / udc;
    if (g < 0.0f)
        g = 0.0f;
    if (g > 2047.0f)
        g = 2047.0f;
    sineB.gain = g;
}

//---------------------------------------------------------------------------
// Авария. Вызывается из прерывания, поэтому здесь ничего тяжёлого:
// закрыть выход (m = 0 даст нулевое напряжение на мосту в течение одного
// периода ШИМ) и оставить заявку фону. Ни IGBT*_Disable(), ни
// RegisterSessionEvent() из ISR звать нельзя - первые делают EINT внутри
// себя (вложенное прерывание посреди ISR), вторая лезет в журнал и историю.
//---------------------------------------------------------------------------
void grid_tie_fault(uint16_t code)
{
    if (gt.State != GT_FAULT)
    {
        gt.fault    = code;
        gt.faultNew = 1;
    }
    gt.State       = GT_FAULT;
    gt.Iset        = 0.0f;
    gt.m           = 0.0f;
    gt.acContactor = 0;
    gt.shutdownReq = 1;

    gt.pr.x1 = 0.0f;
    gt.pr.x2 = 0.0f;
}

//---------------------------------------------------------------------------
// Режим, собранный из двух флагов. Отдельной переменной под него нет
// намеренно: она неизбежно разъехалась бы с gridMode и connReq, которые и так
// правятся из нескольких мест (аварии, снятие разрешения, останов).
//---------------------------------------------------------------------------
uint16_t grid_mode_get(void)
{
    if (!gridMode)
        return GRID_MODE_OFF;

    return gt.connReq ? GRID_MODE_GRID : GRID_MODE_SYNC;
}

void grid_tie_start(void)
{
    if (gt.State == GT_OFF)
    {
        gt.syncCnt     = 0;
        gt.startDelay  = 0;
        gt.acContactor = 0; // замкнётся только по команде оператора
        // Запрос выхода в сеть при включении слежения снимаем. Иначе мост,
        // едва набрав синхронизм, ушёл бы в сеть по запросу, отданному до
        // прошлого останова, - а оператор ждёт от слежения холостого хода.
        gt.connReq     = 0;
        gt.Iset        = 0.0f;
        gt.pr.x1       = 0.0f;
        gt.pr.x2       = 0.0f;
        gt.State       = GT_SYNC;

        // Поправку постоянки начинаем с нуля. Прямая запись mDC тут не
        // годится: раз в сто тактов она пришлась бы на тот самый такт, где
        // mDC пишет CLA, и сброс молча пропал бы. Просим её сама.
        dcResetReq++;

        // Состояние модели здесь больше не сбрасывается. Модель - это железо,
        // а железо от нажатия кнопки "пуск" токи себе не обнуляет: при
        // разомкнутом контакторе ток вторички и так ноль, а намагничивание
        // живёт своей жизнью, пока мост модулирует.
    }
}

void grid_tie_stop(void)
{
    gt.State       = GT_OFF;
    gt.fault       = 0;
    gt.faultNew    = 0;
    gt.Iset        = 0.0f;
    gt.m           = 0.0f;
    gt.syncCnt     = 0;
    gt.startDelay  = 0;
    gt.acContactor = 0;
    gt.connReq     = 0;
    gt.pr.x1       = 0.0f;
    gt.pr.x2       = 0.0f;
    gt.shutdownReq = 1;
}

//---------------------------------------------------------------------------
// Фоновая часть: то, чему не место в прерывании.
// Вызывается из while(1) в main.c.
//---------------------------------------------------------------------------
void grid_tie_background(void)
{
    // Команда из отладчика. Стоит ПЕРЕД разбором shutdownReq не случайно:
    // grid_tie_stop() его как раз и взводит, и ключи должны закрыться в этом
    // же проходе фона, а не в следующем.
    if (gtCmd)
    {
        uint16_t cmd = gtCmd;
        gtCmd        = 0;

        // Автомат живёт в прерывании, поэтому его состояние меняем с
        // закрытыми прерываниями. Иначе такт контура успеет влезть между
        // сбросом резонатора и сменой State и досчитает период с
        // полуобнулённым состоянием.
        DINT;
        if (cmd == 1)
            grid_tie_stop();
        else if (cmd == 2)
            grid_tie_start();
        EINT;
    }

    if (gt.shutdownReq)
    {
        gt.shutdownReq = 0;
        IGBT1_Disable();
        IGBT2_Disable();
    }

    if (gt.faultNew)
    {
        gt.faultNew = 0;
        RegisterSessionEvent(gt.fault);
    }

    //-----------------------------------------------------------------
    // Упор поправки постоянки. ЗАПИСЬ В ЖУРНАЛ, БЕЗ ОСТАНОВА.
    //
    // Что это значит. mDCmax выбран из "сколько нужно для компенсации"
    // (мёртвое время просит 0.01, взят двойной запас), а НЕ из "сколько
    // сердечник стерпит". Значит упор - это не "контур старается", а
    // "помеха больше всех моих полномочий": контур делает что может и
    // проигрывает, поток каждый период стоит не по центру.
    //
    // Почему не авария. Ключи бережёт компаратор CMPSS2 по линии TRIP5,
    // аппаратно; на обвал индуктивности программа не успевает в принципе,
    // и подменять её тут нечем. А то, что ловит этот счётчик, - случай
    // ХРОНИЧЕСКИЙ: сердечник у колена, лишние потери, искажённая форма,
    // но ток целиком под порогом компаратора, потому что тот стоит на
    // 30 % выше приведённого тока нагрузки, и запас этот заведён как раз
    // под ток намагничивания. Останавливать по нему мост - решение
    // отдельное и пока не принятое; разбор - grid_tie.txt, 3.1.5.
    //
    // Зовётся отсюда, а не из grid_tie_onGridZero(), где живёт проверка
    // gt_mSat: ту функцию взводит захват нуля сети, и в АИН без сети она
    // может не отработать ни разу. А первым с железом включат как раз АИН.
    // Фон же крутится в while(1) безусловно. Заодно только отсюда и можно
    // звать RegisterSessionEvent() - из ISR ей в журнал нельзя.
    //
    // По фронту: фон проходит тысячи раз за то время, пока серия держится.
    //-----------------------------------------------------------------
    static uint16_t dcSatSeen = 0;

    if (dcSatCnt > dcSatLimit)
    {
        if (!dcSatSeen)
        {
            dcSatSeen = 1;
            RegisterSessionEvent(gt_dcSat);
        }
    }
    else if (dcSatCnt == 0)
    {
        // Взводим обратно только на полном выходе из упора, а не как только
        // счётчик опустился ниже порога: иначе дрожание около него дало бы
        // очередь записей об одном и том же событии.
        dcSatSeen = 0;
    }
}

//---------------------------------------------------------------------------
// Измерения тракта: напряжение сети и напряжение звена.
//
// Живут отдельно от такта контура, потому что нужны РАНЬШЕ него: следом за
// этой функцией и до grid_tie_step() идёт такт модели, которому gt.uGrid
// служит ЭДС сети. Разбор - в объявлении в grid_tie.h.
//
// Зовётся в обоих режимах моста, в том числе в АИН: обе величины полезны как
// показания и стоят недорого.
//---------------------------------------------------------------------------
#pragma CODE_SECTION(grid_tie_measure, ".TI.ramfunc");

void grid_tie_measure(void)
{
    // Напряжение сети. Берём СЫРОЙ отсчёт и вычитаем измеренный ноль.
    // ADCPPB1RESULT здесь не годится: в ADCPPB1OFFREF лежит калибровочный
    // офсет канала (110), а не середина шкалы, так что "знаковый" результат
    // PPB несёт постоянное смещение почти в 2000 кодов. С ним индекс
    // модуляции полпериода стоит в упоре по mMax.
    gt.uGridKod = (int16_t)((float)u220_kod - gt.u220Zero);
    gt.uGrid    = gt.kU220 * (float)gt.uGridKod;

    // Напряжение АКБ. Мгновенное, не сглаженное - см. комментарий в grid_tie.h.
    if (gt.UdcSrc)
    {
        // На модели канал uBat пишет plant_sim_step(), и лезть за ним в
        // регистр PPB бессмысленно: там висит реальный вход, на стенде ни к
        // чему не подключённый. Значение прошлого такта для напряжения АКБ -
        // не запаздывание, а то же самое число.
        gt.Udc = sim.on ? uBat_volt
                        : kadcf.uBat * (float)(int16_t)AdcaResultRegs.ADCPPB2RESULT.bit.PPBRESULT;
    }
    else
    {
        gt.Udc = gt.UdcFixed;
    }

    //-----------------------------------------------------------------
    // Разрешение контуру подавления постоянки править mDC. Сам контур
    // считает CLA, а знание о том, работает ли мост, живёт здесь - вот
    // и весь обмен: одно слово в такт.
    //
    // Место выбрано потому, что эта функция - единственная, которую
    // зовут КАЖДЫЙ ТАКТ И В ОБОИХ РЕЖИМАХ. Дальше по такту дороги
    // расходятся: в сети grid_tie_step(), в острове sine_invertor2().
    //
    // В СЕТИ разрешаем во всех состояниях, где мост модулирует, включая
    // GT_SYNC. Раньше GT_SYNC был исключён, и это была дыра: контактор
    // там разомкнут, но мост уже работает, поток копится, а следить за
    // ним некому, причём не меньше полусекунды (syncNeed). Разбор -
    // grid_tie.txt, 3.1.7.
    //
    // В ОСТРОВЕ признак один - открытые ключи. При закрытых тока нет
    // вовсе (на модели он тождественно ноль, на железе остаётся
    // смещение нуля датчика), и интегратор уехал бы в потолок,
    // компенсируя то, чего не существует.
    //-----------------------------------------------------------------
    dcAllow = gridMode ? ((gt.State == GT_SYNC) || (gt.State == GT_RAMP) ||
                          (gt.State == GT_RUN))
                       : motors[0]->flag.bit.pwm_On;
}

//---------------------------------------------------------------------------
// Такт контура тока. Вызывается из INT_myADCB_1_ISR, 100 раз за период сети,
// следом за grid_tie_measure() и тактом модели plant_sim_step().
//
// Порядок важен: сначала модель отрабатывает ПРЕДЫДУЩИЙ индекс модуляции
// (тот, что реально стоял в CMPA последний период), и только потом считается
// новый. Иначе модель окажется на такт быстрее реальности.
//---------------------------------------------------------------------------
#pragma CODE_SECTION(grid_tie_step, ".TI.ramfunc");

void grid_tie_step(void)
{
    // Измерения уже сделаны grid_tie_measure(), токи - либо прочитаны с АЦП
    // в xfmr_currents_from_adc(), либо подменены моделью в plant_sim_step().

    //-----------------------------------------------------------------
    // 1. Защиты. Работают всегда, в любом состоянии.
    //-----------------------------------------------------------------
    if (++gt.noGrid > gt.noGridMax)
    {
        // Захватов eCAP нет больше полутора периодов. Без этой проверки
        // TBPRD и step замирают на последних значениях, а мост продолжает
        // работать "по памяти" - в сеть так нельзя.
        gt.noGrid = gt.noGridMax; // не даём переполниться
        if (gt.State == GT_RAMP || gt.State == GT_RUN)
            grid_tie_fault(gt_noGrid);
    }

    if (gt.State == GT_RAMP || gt.State == GT_RUN)
    {
        if (fabsf(iPri_amp) > gt.ImaxPri)
            grid_tie_fault(gt_overIpri);
        else if (fabsf(iSec_amp) > gt.ImaxSec)
            grid_tie_fault(gt_overIsec);
        else if (gt.UdcSrc && ((gt.Udc < gt.UdcMin) || (gt.Udc > gt.UdcMax)))
            grid_tie_fault(gt_UdcRange);
    }

    //-----------------------------------------------------------------
    // 2. Контур тока
    //-----------------------------------------------------------------
    // GT_SYNC тоже считает контур, но с нулевой уставкой. Смысл: мост уже
    // модулирует и активно держит нулевой ток, то есть его напряжение само
    // подстраивается под сетевое. К моменту замыкания контактора разность
    // на его контактах нулевая, и переход в GT_RAMP получается безударным -
    // уставка просто начинает расти от нуля.
    if (gt.State == GT_SYNC || gt.State == GT_RAMP || gt.State == GT_RUN)
    {
        // Угол сети - тот же, по которому идёт вся синхронизация.
        // Берём ДО приращения, как это делает sine_invertor1().
        float theta = sineB.angle + sineB.offset;
        float s     = sinf(theta);

        gt.iref = (gt.State == GT_SYNC) ? 0.0f : (gt.Iset * s);
        if ((gt.Iq != 0.0f) && (gt.State != GT_SYNC))
            gt.iref += gt.Iq * cosf(theta);

        gt.ierr = gt.iref - iSec_amp;

        // PR: пропорциональная часть плюс резонатор ровно на частоте сети.
        // Состояние сохраняем - при упоре по m его придётся откатить.
        float x1old = gt.pr.x1;
        float x2old = gt.pr.x2;

        gt.pr.x1 += gt.pr.step * gt.pr.x2 + gt.pr.KiTs * gt.ierr - gt.pr.leak * gt.pr.x1;
        gt.pr.x2 -= gt.pr.step * gt.pr.x1;

        if (gt.pr.x1 > gt.pr.xMax)
            gt.pr.x1 = gt.pr.xMax;
        else if (gt.pr.x1 < -gt.pr.xMax)
            gt.pr.x1 = -gt.pr.xMax;

        gt.pr.out = gt.pr.Kp * gt.ierr + gt.pr.x1;

        // Прямая связь по сети снимает с регулятора всю основную синусоиду:
        // PR остаётся отрабатывать только падение на индуктивности рассеяния,
        // а это единицы вольт.
        gt.uSec = gt.uGrid + gt.pr.out;

        // Коэффициент трансформации входит ровно один раз, здесь.
        float denom = gt.n * gt.Udc;
        gt.m        = (denom > 1.0f) ? (gt.uSec / denom + mDC) : 0.0f;

        if ((gt.m > gt.mMax) || (gt.m < -gt.mMax))
        {
            gt.m = (gt.m > 0.0f) ? gt.mMax : -gt.mMax;

            // Упор. Интегратор в упоре наматывать не должен - откатываем.
            gt.pr.x1 = x1old;
            gt.pr.x2 = x2old;
            gt.satCount++;
        }

    }
    else
    {
        // GT_OFF / GT_FAULT: оба плеча на 50 %, напряжение моста равно нулю.
        gt.m      = 0.0f;
        gt.pr.out = 0.0f;
    }

    // Отсчёт четверти периода от нуля напряжения до замыкания контактора -
    // см. взвод startDelay в grid_tie_onGridZero(). Поток есть интеграл
    // напряжения, поэтому замыкание в максимуме даёт нулевое начальное
    // смещение потока.
    if ((gt.State == GT_SYNC) && (gt.startDelay > 0))
    {
        if (--gt.startDelay == 0)
        {
            gt.Iset        = 0.0f;
            gt.acContactor = 1;
            gt.State       = GT_RAMP;
        }
    }

    //-----------------------------------------------------------------
    // 3. Вывод в компараторы
    //
    // Режим UP_DOWN, UP_CMPA -> HIGH, DOWN_CMPA -> LOW, значит доля высокого
    // уровня плеча = 1 - CMPA/TBPRD. При CMPA_A = TBPRD*(1-m)/2 получается
    // dA = (1+m)/2, dB = (1-m)/2 и U_AB = m*Udc.
    //
    // Окна открытого состояния обоих плеч отцентрированы по вершине счётчика,
    // поэтому узкое вложено в широкое: U_AB принимает только 0 и +Udc (либо
    // 0 и -Udc). Это трёхуровневая модуляция, частота пульсации вдвое выше
    // несущей. Ломать это соотношение CMPA нельзя.
    //-----------------------------------------------------------------
    {
        uint16_t tbprd = EPwm1Regs.TBPRD;
        float    ca    = (float)tbprd * 0.5f * (1.0f - gt.m);

        if (ca < 0.0f)
            ca = 0.0f;
        else if (ca > (float)tbprd)
            ca = (float)tbprd;

        cmpaA = (uint16_t)ca;
        cmpaB = tbprd - cmpaA;

        EPwm1Regs.CMPA.bit.CMPA = cmpaA;
        EPwm2Regs.CMPA.bit.CMPA = cmpaB;
    }

    //-----------------------------------------------------------------
    // 4. Угол.
    //
    // В обычном режиме его двигают sine_invertor1/2. Раз мы их заменили,
    // двигать обязаны сами - иначе встанет весь PLL: и подстройка фазы,
    // и dacb, и детектор нуля.
    //-----------------------------------------------------------------
    sineB.angle = asut(sineB.angle + sineB.step);

    //-----------------------------------------------------------------
    // 5. Трассировка формы. Четыре записи в ОЗУ, на такт незаметно.
    //
    // Пишется в самом конце: к этому моменту в gt лежит согласованный
    // срез одного и того же такта - iref, измеренный ток и тот m, который
    // только что ушёл в CMPA.
    //-----------------------------------------------------------------
    if (gtTrcRun)
    {
        gtTrcIref[gtTrcIdx] = gt.iref;
        gtTrcIb[gtTrcIdx]   = iSec_amp;
        gtTrcIa[gtTrcIdx]   = iPri_amp;
        gtTrcM[gtTrcIdx]    = gt.m;

        if (++gtTrcIdx >= GT_TRC_LEN)
        {
            gtTrcIdx = 0;
            if (gtTrcRun == 2)
                gtTrcRun = 0; // однократный снимок сделан
        }
    }
}

//---------------------------------------------------------------------------
// Раз за период сети, из INT_U220_zero_ECAP_ISR.
// Здесь живёт всё медленное: автомат и нарастание уставки.
//
// Контура DC здесь больше нет. Он уехал в Cla1Task1 целиком - и усреднение,
// и интегратор, и ограничение, - а вместе с ним ушли обе обёртки, которые
// стояли тут: grid_tie_mdc_period() для сети и grid_tie_dc_island() для
// острова. Держать два окна на одну величину было нечем оправдать: окно CLA
// (rmsWindow тактов) годится обоим, разбор - grid_tie.txt, 3.1.4.
//---------------------------------------------------------------------------
void grid_tie_onGridZero(void)
{
    // Сеть есть - сторож перезаряжен.
    gt.noGrid = 0;

    //-----------------------------------------------------------------
    // Пересчёт периода дискретизации и коэффициентов, зависящих от него.
    // TBPRD правится тем же прерыванием при каждом захвате, так что Ts
    // надо освежать здесь же.
    //-----------------------------------------------------------------
    gt.Ts      = (float)EPwm1Regs.TBPRD * (1.0f / TB1_TICKS_PER_SECOND_HALF);
    gt.pr.KiTs = gt.pr.Ki * gt.Ts;
    gt.pr.step = sineB.step; // резонанс автоматически едет за частотой сети

    // Ноль канала U220 - середина вилки огибающей. Вилка живёт в myADC.c
    // и обхватывает реальный сигнал сверху и снизу, так что её середина и
    // есть измеренный ноль. Обновляем раз за период: чаще незачем, а к
    // калибровочному офсету PPB привязываться нельзя (см. grid_tie.h).
    gt.u220Zero = ((float)u220hi_kod + (float)u220low_kod) * 0.5f;

    //-----------------------------------------------------------------
    // Качество синхронизма за прошедший период
    //-----------------------------------------------------------------
    uint16_t gridOk = ((u220freq >= gt.freqMin) && (u220freq <= gt.freqMax) &&
                       (u220amp >= gt.ampMin) && (u220amp <= gt.ampMax) &&
                       (fabsf(phaseErr) < gt.phaseOk))
                          ? 1U
                          : 0U;

    // dbg Разложение того же условия по причинам. Условия ЗЕРКАЛЬНЫ к gridOk
    // выше (там >= и <=, здесь < и >), иначе значение на самой границе окна
    // дало бы gridOk = 0 при пустой маске - и разбор увёл бы не туда.
    //
    // В GT_FAULT замирает: маска и нужна как снимок момента срыва. Смысл
    // битов и комбинаций - в grid_tie.h.
    if (gt.State != GT_FAULT)
    {
        gt.syncBad = (((u220freq < gt.freqMin) || (u220freq > gt.freqMax)) ? 1U : 0U) |
                     (((u220amp < gt.ampMin) || (u220amp > gt.ampMax)) ? 2U : 0U) |
                     ((fabsf(phaseErr) >= gt.phaseOk) ? 4U : 0U);
    }

    //-----------------------------------------------------------------
    // Систематический упор по m - это не помеха, а диагноз: либо просел
    // АКБ, либо мал коэффициент трансформации, либо сердечник не тянет.
    // Тихо портить форму тока в такой ситуации нельзя.
    //-----------------------------------------------------------------
    gt.satLast  = gt.satCount;
    gt.satCount = 0;

    //-----------------------------------------------------------------
    // Уход из сети обратно в слежение.
    //
    // Оператор снял запрос (кнопка "Откл.") или разрешение (галочка Enable):
    // размыкаем контактор и возвращаемся в GT_SYNC. Это НЕ авария - мост
    // продолжает модулировать клон сети вхолостую, и следующий выход в сеть
    // не требует ни сброса аварии, ни перезапуска слежения.
    //
    // syncCnt обнуляем: качество захвата после коммутации надо набрать
    // заново, иначе повторное замыкание случилось бы в тот же период.
    //
    // Ток сбрасывается разом, без рампы - так же, как в grid_tie_stop().
    // Пока acContactor живёт только в модели, это безразлично; когда под реле
    // выделят GPIO, размыкание придётся делать по нулю тока, а до него
    // спускать Iset рампой.
    if (((gt.State == GT_RAMP) || (gt.State == GT_RUN)) && (!gt.connReq || !gt.gridEn))
    {
        gt.acContactor = 0;
        gt.Iset        = 0.0f;
        gt.syncCnt     = 0;
        gt.startDelay  = 0;
        gt.State       = GT_SYNC;

        // Поправку постоянки - с нуля, как и при пуске. Запросом, а не
        // прямой записью: mDC теперь хозяйство CLA.
        dcResetReq++;
    }

    switch (gt.State)
    {
        case GT_SYNC:
            if (gridOk)
            {
                if (gt.syncCnt < gt.syncNeed)
                    gt.syncCnt++;

                // Условие взвода - именно ">=", а не "==". syncNeed объявлен
                // крутилкой отладчика, и если его понизить на ходу, счётчик
                // окажется уже выше порога: со строгим равенством пуск после
                // этого не наступит никогда.
                // Повторный взвод невозможен: замыкание контактора выводит
                // автомат из GT_SYNC и ставит acContactor.
                //
                // Синхронизм больше не пускает в сеть сам. Набранный syncCnt -
                // это разрешение автомата, а решение принимает оператор:
                // connReq (кнопка "Сеть") при поднятом gridEn (галочка Enable).
                // Без них автомат остаётся в GT_SYNC сколь угодно долго - в
                // этом и смысл слежения: мост держит клон сети вхолостую, и
                // его можно спокойно сверить с сетью осциллографом.
                if ((gt.syncCnt >= gt.syncNeed) && (gt.startDelay == 0) &&
                    (gt.acContactor == 0) && gt.connReq && gt.gridEn)
                {
                    // Пуск смещён на четверть периода от нуля напряжения,
                    // то есть в его максимум: поток - интеграл напряжения,
                    // и замыкание в максимуме даёт нулевое начальное смещение.
                    // Досчитывает startDelay уже grid_tie_step().
                    gt.startDelay = sineB.resolution / 4;
                }
            }
            else
            {
                gt.syncCnt    = 0;
                gt.startDelay = 0;
            }
            break;

        case GT_RAMP:
            if (!gridOk)
            {
                grid_tie_fault(gt_syncLost);
                break;
            }
            if (gt.satLast > gt.satLimit)
            {
                grid_tie_fault(gt_mSat);
                break;
            }

            // Рампа в обе стороны. Скачок вниз перегрузки не даёт, но резкий
            // сброс тока - это ступенька напряжения на индуктивности рассеяния
            // и лишний бросок в сердечник. Спускаемся так же плавно.
            if (gt.Iset < gt.IsetRef)
            {
                gt.Iset += gt.IsetSlew;
                if (gt.Iset >= gt.IsetRef)
                {
                    gt.Iset  = gt.IsetRef;
                    gt.State = GT_RUN;
                }
            }
            else if (gt.Iset > gt.IsetRef)
            {
                gt.Iset -= gt.IsetSlew;
                if (gt.Iset <= gt.IsetRef)
                {
                    gt.Iset  = gt.IsetRef;
                    gt.State = GT_RUN;
                }
            }
            else
            {
                gt.State = GT_RUN;
            }
            break;

        case GT_RUN:
            if (!gridOk)
            {
                grid_tie_fault(gt_syncLost);
                break;
            }
            if (gt.satLast > gt.satLimit)
            {
                grid_tie_fault(gt_mSat);
                break;
            }

            // Уставку можно менять на ходу, но только через нарастание.
            if (gt.Iset != gt.IsetRef)
                gt.State = GT_RAMP;
            break;

        case GT_OFF:
        case GT_FAULT:
        default:
            gt.syncCnt = 0;
            break;
    }
}
