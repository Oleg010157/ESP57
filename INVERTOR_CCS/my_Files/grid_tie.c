    // СОСТОЯНИЕ: накопители, разрешения, счётчики упора.
    //
    // САМИ КОЭФФИЦИЕНТЫ ЗДЕСЬ БОЛЬШЕ НЕ ЗАДАЮТСЯ - с 25.09.2026 они приходят
    // из структуры reg (my_Files/power_par.h) и переживают выключение: их
    // подбирают под конкретное железо, и терять подбор при снятии питания
    // так же обидно, как терять калибровку АЦП. Заводские значения и довод
    // по каждому числу переехали в power_par.c, к pwr_default.
    //
    // Раздаёт их power_par_apply(), зовёт его main() после этой функции.
    //-----------------------------------------------------------------
    mDC        = 0.0f;
    mDCi       = 0.0f;
    dcAllow    = 0;
    dcResetReq = 0;
    dcSatCnt   = 0;

    uOutAllow    = 0;
    uOutResetReq = 0;
