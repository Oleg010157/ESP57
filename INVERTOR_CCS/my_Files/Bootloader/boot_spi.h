/*****************************************************************************
 * boot_spi.h
 *
 * Второй канал загрузчика: SPIA до WiFi-моста (ESP32) вместо CAN.
 *
 * Протокол загрузчика не меняется ни на слово - те же команды, квитанции и
 * кадры, что в can_boot_protocol.h. Меняется только то, чем кадры возят:
 * вместо Message RAM MCAN - посылка SPI в формате рабочего канала
 * (docs/esp32-spi-protocol-RU.md): метка 0xA55A, номер, длина, кадры
 * «номер, длина, данные». Кадр ПК -> MCU лежит в посылке под номером 0x33,
 * MCU -> ПК - под номером 0x32, как на шине.
 *
 * Ведёт обмен мост, а не ПК: образ прошивки он принимает по WiFi целиком,
 * проверяет и только потом зовёт прибор в загрузчик (ESP32_BRIDGE/main/
 * fwup.c). Обрыв WiFi посреди прошивки поэтому ничего не портит.
 *
 * Вход - кадр BOOT_SPI_ENTER под номером 0x33 в посылке от моста. Из сети
 * его прислать нельзя: мост пропускает к прибору только команды (ID 2), а
 * 9999 по WiFi прибор не выполняет вовсе (wifi_link.c).
 *
 * Обмен опросом, без DMA и прерываний: прибор - ведущий, посылка уходит,
 * когда загрузчику нужен кадр или копится, что отправить. Всё в .TI.ramfunc и
 * на прямых обращениях к регистрам - по той же причине, что и у CAN-части:
 * флеш будет стёрт (разбор в CAN_Bootloader_Protocol.md).
 *****************************************************************************/
#ifndef BOOT_SPI_H_
#define BOOT_SPI_H_

#include <stdint.h>
#include <stdbool.h>

/* Вход в загрузчик по SPI: кадр 0x33 [BOOT_SPI_ENTER, BOOT_SPI_KEY, 0, 0]. */
#define BOOT_SPI_ENTER  0xB007U
#define BOOT_SPI_KEY    0x5350U /* 'SP' */

/* Остановить DMA рабочего канала и подготовить SPIA к опросу. Один раз,
 * вместо boot_can_init(). */
void boot_spi_init(void);

/* Следующий кадр от моста: слова в dst (32 слова места), *bytes - длина.
 * false - кадра нет. Пусто - сама проводит обмен. */
bool boot_spi_take(volatile uint16_t *dst, volatile uint16_t *bytes);

/* Служебный кадр к мосту. Уходит со следующей посылкой. */
void boot_spi_send(uint16_t w0, uint16_t w1, uint16_t w2, uint16_t w3);

/* Отдать всё накопленное - перед переходом в новую прошивку. */
void boot_spi_flush(void);

#endif /* BOOT_SPI_H_ */
