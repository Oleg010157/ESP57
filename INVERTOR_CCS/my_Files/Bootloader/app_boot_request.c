/*****************************************************************************
 * app_boot_request.c
 *
 * Точка входа приложения в CAN-загрузчик.
 *
 * Команда 9999 по CAN взводит request_firmware_update (KSP/MBOX28.c), фоновый
 * цикл main() зовёт эту функцию. Она закрывает силовую часть, запрещает
 * прерывания и уходит в bootloader_main().
 *
 * ПОЧЕМУ ИЗ ФОНА, А НЕ ИЗ ОБРАБОТЧИКА. cmd_MBOX28() выполняется в прерывании
 * MCAN, а загрузчик работает опросом и сам перенастраивает тот же MCAN. Уйти
 * туда прямо из обработчика значит не выйти из него никогда - PIE останется
 * взведённым. По той же причине через флаг работают calibCmd, gtCmd и pwrCmd.
 *
 * ПЕРЕЗАГРУЗКА НЕ НУЖНА. Код загрузчика и Flash API уже лежат в ОЗУ: их
 * скопировал Device_init() при старте вместе со всей .TI.ramfunc.
 *
 * ВОЗВРАТА НЕТ. bootloader_main() заканчивается переходом на _c_int00 новой
 * прошивки по адресу, который прислал ПК. Код после его вызова недостижим и
 * оставлен страховкой на случай, если загрузчик когда-нибудь научится
 * отказываться от работы.
 *
 *****************************************************************************/

#include "driverlib.h"
#include "device.h"
#include "f28p55x_device.h"

/* bootloader_main() определён в can_bootloader.c, выполняется из ОЗУ */
extern void bootloader_main(void);

/* IGBT disable — определены в myEPWM.h */
extern void IGBT1_Disable(void);
extern void IGBT2_Disable(void);

#pragma CODE_SECTION(app_request_firmware_update, ".TI.ramfunc")

void app_request_firmware_update(void)
{
    /* 1. Безопасность: закрываем мост. */
    IGBT1_Disable();
    IGBT2_Disable();

    /* 2. Запрещаем прерывания. Остальное глушит сам bootloader_main():
     *    CLA, прерывание АЦП, такт ШИМ и IER. */
    DINT;

    /* 3. Переход в загрузчик. Он перенастроит MCAN под ID 0x33/0x32 и начнёт
     *    обмен с ПК. */
    bootloader_main();

    /* Сброс регистром, а не SysCtl_resetDevice().
     *
     * Та функция при -Ooff выносится компилятором в .text, то есть во флеш, и
     * оказалась бы стёртой ровно к тому моменту, когда понадобится. Пути сюда
     * нет, но если он однажды появится, то появится он именно после неудачной
     * прошивки - в состоянии, когда во флеше недописанный образ. Уход в
     * стёртую память вместо сброса был бы худшим из возможных исходов.
     *
     * Неверное контрольное значение в WDCR вызывает сброс от сторожевого
     * таймера - это и есть реализация SysCtl_resetDevice(), переписанная сюда
     * теми же двумя записями. */
    EALLOW;
    WdRegs.WDCR.all = 0x0028U;  /* включить сторож с верными WDCHK */
    WdRegs.WDCR.all = 0x0000U;  /* неверные WDCHK -> немедленный сброс */
    EDIS;

    for (;;)
    {
    }
}
