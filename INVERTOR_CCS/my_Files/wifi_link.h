/*
 * wifi_link.h
 *
 * Канал к радиомодулю ESP32 по SPIA: те же кадры, что идут по CAN FD.
 *
 *---------------------------------------------------------------------------
 * ЗАЧЕМ
 *
 * ESP32 - прозрачный мост SPI <-> WiFi. Каждый кадр прибора уходит и в CAN,
 * и сюда; пульт подключается тем путём, который есть, ничего не переключая.
 * Формат посылки и все решения - docs/esp32-spi-protocol-RU.md, провода и
 * режим SPI - docs/esp32-spi-wiring-RU.md.
 *
 *---------------------------------------------------------------------------
 * КАК ЭТО УСТРОЕНО, В ДВУХ СЛОВАХ
 *
 * Раз в WIFI_LINK_TICKS тактов (2 мс) прерывание такта отдаёт DMA посылку из
 * 256 слов и тут же начинает копить следующую во втором буфере. Процессор
 * байты не гонит и ничего не ждёт.
 *
 * Кадры попадают в посылку двумя путями:
 *
 *   WifiLink_pushFast()  - быстрый кадр 103, из прерывания такта. Сразу в
 *                          посылку; не влез - пропуск, его видно по sineTick.
 *   WifiLink_push()      - всё остальное: ACK, 140, 132. Через очередь, из
 *                          которой фон перекладывает кадры в посылку. Такие
 *                          кадры не теряются, пока очередь не переполнена.
 *
 * Быстрым кадрам отдано не больше 10 мест на посылку - по одному на такт, -
 * остальное очереди. Как именно делится место, разобрано у WL_FAST_MAX в
 * wifi_link.c.
 *
 * Звать их не нужно: Send_mbox(), Send_mbox_FD() и SendAck() в myMCAN.c
 * кладут сюда каждый кадр сами.
 *
 * Итоги - в wifiLink, смотреть в Watch.
 */

#ifndef WIFI_LINK_H_
#define WIFI_LINK_H_

#include <stdint.h>

#define WIFI_LINK_WORDS 256U // посылка, 16-битных слов
#define WIFI_LINK_TICKS 10U  // тактов на посылку: 10 x 200 мкс = 2 мс

typedef struct
{
    uint32_t sent;       // посылок отдано DMA
    uint32_t notReady;   // ESP32 не готова (ножка «есть данные» высокая) - обмен пропущен
    uint32_t busy;       // прошлая посылка ещё идёт - обмен пропущен
    uint32_t fastDrop;   // быстрых кадров не влезло
    uint32_t queueDrop;  // остальных кадров не влезло в очередь - ПОТЕРЯНЫ
    uint32_t rxOk;       // ответ ESP32 с верной меткой и CRC
    uint32_t rxBad;      // ответ без метки 0x5AA5
    uint32_t rxCrcBad;   // метка есть, CRC или длина не сошлись - ничего не выполнено
    uint32_t cmdIn;      // команд из WiFi выполнено
    uint32_t cmdRejected; // команд из WiFi отклонено: 9999 и 7100, см. wifi_link.c
    uint32_t rxMissed;   // ответ затёрт следующим до разбора - фон не успел
    uint16_t maxFill;    // наибольшая заполненность посылки, слов
    uint16_t maxQueue;   // наибольшая заполненность очереди, слов
    uint16_t startTime;  // dbg запуск посылки в такте, тиков EPWM7 (6,7 нс)
    uint16_t startMax;   // dbg наибольший из них
} WifiLinkStat;

extern volatile WifiLinkStat wifiLink;

// Один раз после Board_init(): канал DMA передачи, см. wifi_link.c.
void WifiLink_init(void);

// Из прерывания такта, КАЖДЫЙ такт. Раз в WIFI_LINK_TICKS запускает обмен.
void WifiLink_tick(void);

// Из фона: перекладывает очередь в посылку, разбирает ответ ESP32.
void WifiLink_background(void);

// Быстрый кадр: из прерывания такта. numWords - слов данных.
void WifiLink_pushFast(uint16_t id, const uint16_t *w, uint16_t numWords);

// Остальные кадры: из любого места. Порядок между ними сохраняется.
void WifiLink_push(uint16_t id, const uint16_t *w, uint16_t numWords);

#endif /* WIFI_LINK_H_ */
