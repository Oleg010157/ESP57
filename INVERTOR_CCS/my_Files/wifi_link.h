/*
 * wifi_link.h
 *
 * Канал к радиомодулю ESP32 по SPIA. Пока - только проверка канала.
 *
 *---------------------------------------------------------------------------
 * ЗАЧЕМ
 *
 * ESP32 будет прозрачным мостом SPI <-> WiFi: прибор отдаёт ему те же кадры,
 * что идут по CAN FD. Прежде чем строить на канале формат посылки, надо
 * убедиться, что сами байты доходят без искажений в обе стороны. Схема
 * проводов и разбор режима SPI - docs/esp32-spi-wiring-RU.md.
 *
 *---------------------------------------------------------------------------
 * ПРОВЕРКА КАНАЛА
 *
 * Раз в 50 мс прибор отправляет посылку из 16 слов (32 байта, ровно FIFO):
 *
 *   [0]     0xA55A          - метка прибора
 *   [1]     seq             - номер посылки
 *   [2..15] seq + i*0x0101  - узор, по которому видна каждая ошибка в бите
 *
 * ESP32 ведомый и успевает подготовить ответ только к СЛЕДУЮЩЕЙ посылке,
 * поэтому в ответ приходит эхо ПРЕДЫДУЩЕЙ: та же посылка, но с меткой 0x5AA5
 * в слове 0. Прибор сверяет её с тем, что отправлял прошлый раз, - так
 * проверяется POCI. PICO проверяет сама ESP32 по узору и печатает итог в
 * свой COM-порт.
 *
 * Итоги лежат в wifiLink - смотреть в Watch.
 */

#ifndef WIFI_LINK_H_
#define WIFI_LINK_H_

#include <stdint.h>

#define WIFI_LINK_WORDS 16U // посылка = весь FIFO SPIA

typedef struct
{
    uint16_t seq;     // номер следующей посылки
    uint32_t ok;      // эхо совпало с прошлой посылкой
    uint32_t noEsp;   // нет метки 0x5AA5: ESP32 не ответила или байты сдвинуты
    uint32_t seqMiss; // метка есть, но эхо не той посылки - ESP32 пропустила обмен
    uint32_t bad;     // эхо той посылки, но данные искажены
    uint32_t timeout; // FIFO приёма не заполнился - SPIA не тактирует
    uint16_t rdy;     // уровень GPIO55 «есть данные» в момент обмена
    uint16_t rx[WIFI_LINK_WORDS]; // последний ответ как есть, для разбора глазами
} WifiLinkStat;

extern volatile WifiLinkStat wifiLink;

// Звать из 50-мс тика фона. Занимает около 70 мкс (32 байта на 4,17 МГц).
void WifiLink_tick50ms(void);

#endif /* WIFI_LINK_H_ */
