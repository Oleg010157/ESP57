#ifndef PLANT_SIM_H_
#define PLANT_SIM_H_

#include <stdint.h>

//---------------------------------------------------------------------------
// Что висит на выходе моста, когда контактор РАЗОМКНУТ (режим АИН и слежение).
// При замкнутом контакторе нагрузкой служит сеть, и эти строки не при делах.
//---------------------------------------------------------------------------
#define LOAD_OFF 0U // холостой ход: цепи нет, ток тождественно нулевой
#define LOAD_R   1U // активная: один резистор
#define LOAD_RL  2U // активно-индуктивная: резистор последовательно с дросселем

//---------------------------------------------------------------------------
// Модель описывает ЖЕЛЕЗО, а не представления контура о нём.
//
// Это главное, что надо понять про эту структуру. У контура есть свои числа -
// gt.n и gt.UdcFixed, - и на живой машине они должны совпадать с настоящими.
// Здесь лежат настоящие. Разведены они нарочно: расхождение между тем, что
// стоит на столе, и тем, что контур о нём думает, - это отдельный опыт, и
// отдельные строки таблицы позволяют поставить его в одно нажатие.
//
//     sim.Udc = 35, gt.UdcFixed = 48   просевший АКБ, контур о том не знает
//     sim.n   = 8,  gt.n = 7           перемотанный трансформатор
//
// Всё, что можно привести ко вторичке, приведено ко вторичке (сторона 220 В):
// там же живёт контур тока, и лишних коэффициентов в уравнениях не остаётся.
//---------------------------------------------------------------------------
struct Plant
{
    //--- ключ -------------------------------------------------------------
    // 1 = измерения берутся из модели, а не с АЦП. На живом мосте - 0.
    // Подменяются ВСЕ шесть величин тракта: токи первички и вторички,
    // напряжение на выходе инвертора, напряжение и ток АКБ. Канал сети U220
    // не трогается - он ведёт PLL, и на стенде это имитация от ЦАП.
    uint16_t on;

    uint16_t loadType; // LOAD_OFF / LOAD_R / LOAD_RL

    //--- источник ---------------------------------------------------------
    float Udc; // входное напряжение (АКБ), В

    //--- трансформатор, всё приведено ко вторичке --------------------------
    float n;     // коэффициент трансформации Uвтор/Uперв
    float Lleak; // индуктивность рассеяния, Гн
    float Rwind; // активное сопротивление обмоток, Ом

    // Индуктивность намагничивания. 0 = ветви нет, тогда iPri = n*iSec
    // тождественно, как было в прежней модели.
    //
    // Ради неё модель и переписана. Без ветви намагничивания постоянная
    // составляющая напряжения даёт в токе всего лишь постоянный ток через
    // R, то есть ведёт себя как на дросселе. Настоящий трансформатор её
    // ИНТЕГРИРУЕТ в поток, и ток намагничивания уходит линейно - вот это
    // и видит контур подавления DC на первичке. См. grid_tie.txt, 3.1.
    float Lmag;

    //--- нагрузка ---------------------------------------------------------
    float Rload; // Ом
    float Lload; // Гн, участвует только при loadType = LOAD_RL

    // Искусственная постоянная составляющая в приложенном напряжении, В на
    // вторичке. Именно так ведёт себя асимметрия мёртвого времени - это
    // ошибка НАПРЯЖЕНИЯ, а не измерения. Смещение, внесённое в измерение
    // тока, контур занулить не смог бы в принципе: он лишь упёрся бы в mDCmax.
    float uDCinject;

    //--- состояние --------------------------------------------------------
    float iSec; // ток вторички: в нагрузку или в сеть, А
    float iMag; // ток намагничивания, приведён ко вторичке, А

    //--- dbg результат такта ----------------------------------------------
    float m;       // индекс модуляции, отработанный на прошлом такте
    float uBridge; // что мост приложил, приведено ко вторичке, В
    float uSecOut; // что показал бы датчик на выходе инвертора, В
    float iPri;    // ток первички, А
    float iBat;    // ток АКБ, А
    float Ts;      // период такта, с - берётся из TBPRD каждый такт
};

extern struct Plant sim;

// Копия sim.on для CLA живёт в CLA/cla_shared.c рядом с rmsWindow - там же,
// где и остальные параметры направления CPU -> CLA. Зовут её simOn, ставит её
// plant_sim_step(), а нужна она затем, чтобы задача Cla1Task1 отошла в сторону
// от трёх каналов, которые на модели пишет не она.

void plant_sim_init(void);

// Такт модели. Зовётся из INT_myADCB_1_ISR ПЕРЕД тактом управления: модель
// обязана отработать тот индекс модуляции, что реально стоял в компараторах
// последний период, а не тот, который контур посчитает через микросекунду.
void plant_sim_step(void);

#endif /* PLANT_SIM_H_ */
