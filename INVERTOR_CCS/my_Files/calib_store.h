/*
 * calib_store.h
 *
 * Хранение калибровок АЦП в энергонезависимой памяти.
 *
 *---------------------------------------------------------------------------
 * ЗАЧЕМ
 *
 * Нули (offsets) и масштабы (kadc) каналов АЦП должны переживать выключение
 * питания. На шкафу для этого есть внешняя SPI-EEPROM, на LaunchPad её нет -
 * именно поэтому чтение из EEPROM в main.c стоит закомментированным, и прибор
 * каждый раз стартует на заводских значениях.
 *
 * Здесь тот же смысл, но носитель - флеш самого процессора, банк BANK4.
 * Работает одинаково на стенде и на плате.
 *
 *---------------------------------------------------------------------------
 * КАК ЭТО УСТРОЕНО, В ДВУХ СЛОВАХ
 *
 * Флеш нельзя переписать поверх: чтобы изменить уже записанное место, надо
 * сначала стереть весь сектор. Поэтому каждое сохранение пишется в СЛЕДУЮЩУЮ
 * свободную страницу банка, а стирание происходит только когда банк кончился.
 * Эту механику делает код TI в my_Files/flash_eeprom/ - трогать его не нужно.
 *
 * Здесь лежит только то, что касается нас: ЧТО храним (CalibBlob) и как
 * проверяем, что прочитанное не мусор.
 *
 *---------------------------------------------------------------------------
 * КАК ДОБАВИТЬ ПАРАМЕТР
 *
 * 1. Добавить поле в ADCpar (myADC.h) - в КОНЕЦ, перед crc.
 * 2. Всё. Размер страницы во флеше пересчитается сам: DATA_SIZE в
 *    flash_eeprom/EEPROM_Config.h вычисляется как sizeof(CalibBlob).
 *
 * Если новых данных станет столько, что банк не вместит нужное число
 * сохранений, сборка остановится с ошибкой на строке CALIB_FITS_IN_BANK
 * в calib_store.c - там же написано, какое число уменьшать. Молча испортить
 * флеш нельзя: проверка срабатывает при компиляции, а не на железе.
 *
 * Если понадобится хранить что-то ещё, кроме offsets и kadc, - добавьте поле
 * в CalibBlob ниже и увеличьте CALIB_VERSION. Старые записи с прежней версией
 * будут отброшены как несовместимые, и прибор уйдёт на заводские значения.
 * Это правильное поведение: лучше заводские, чем чужой формат, разобранный
 * как свой.
 *
 * ТАК УЖЕ ДЕЛАЛИ ДВАЖДЫ, и оба раза платили одним и тем же - числом страниц:
 *
 *   версия 2, 10.09.2026   добавлен канал uSec. Запись 17 слов вместо 15,
 *                          страниц 72 вместо 80
 *   версия 3, 25.09.2026   добавлены паспорт силовой части и коэффициенты
 *                          регуляторов. Запись 47 слов, страниц 36
 *
 * Запас в банке кончается быстрее, чем кажется: страница несёт ещё 8 слов
 * состояния, а размер данных округляется вверх до кратного четырём (ECC).
 * Зато 36 страниц на 16 банков - это 576 сохранений до первого стирания, а
 * настройку пишут единицы раз за жизнь прибора.
 */

#ifndef CALIB_STORE_H_
#define CALIB_STORE_H_

#include <stdint.h>
#include "myADC.h"    // ADCpar
#include "power_par.h" // PowerPar, RegPar

// Сигнатура. Стёртый флеш читается как 0xFFFF, поэтому любое другое значение
// годится - лишь бы отличалось от 0xFFFF и от 0x0000.
#define CALIB_MAGIC 0x4B57U // 'K','W' - K57

// Версия формата. Менять при ЛЮБОМ изменении состава CalibBlob.
//
//   1  исходный: по пять каналов в offsets и kadc
//   2  10.09.2026, добавлен канал uSec - в обеих структурах стало по шесть
//   3  25.09.2026, добавлены паспорт силовой части и коэффициенты регуляторов
//      (power_par.h). Запись выросла с 17 слов до 47, страниц в банке стало
//      36 вместо 72 - см. EEPROM_Config.h
#define CALIB_VERSION 3U

//---------------------------------------------------------------------------
// Что именно лежит во флеше.
//
// Порядок полей внутри ADCpar менять нельзя (см. myADC.h), а вот порядок
// полей здесь менять можно - но тогда поднимите CALIB_VERSION, иначе старая
// запись будет разобрана неправильно и проверочная сумма этого не поймает:
// сумма не зависит от порядка слагаемых.
//---------------------------------------------------------------------------
typedef struct
{
    uint16_t magic;   // CALIB_MAGIC
    uint16_t version; // CALIB_VERSION
    ADCpar   offsets; // нули каналов АЦП
    ADCpar   kadc;    // масштабы каналов АЦП

    // Настройка ПРИБОРА, а не измерительного тракта. Добавлены 25.09.2026:
    // инвертор перестал быть "трёхкиловаттным с трансформатором 1:7", и
    // описание конкретной машины обязано переживать выключение - прибор
    // работает автономно, без пульта на CAN. Разбор - power_par.h.
    //
    // У каждой структуры СВОЯ контрольная сумма, независимая от общей суммы
    // записи ниже: половины настраиваются порознь, и по нулю в crc видно,
    // какая из них ещё не задавалась.
    PowerPar pwr; // паспорт силовой части
    RegPar   reg; // коэффициенты двух медленных контуров

    uint16_t sum; // сумма всех слов выше. ОБЯЗАНА ОСТАВАТЬСЯ ПОСЛЕДНЕЙ:
                  // calib_sum() считает sizeof - 1 слово
} CalibBlob;

//---------------------------------------------------------------------------
// Результат чтения
//---------------------------------------------------------------------------
typedef enum
{
    CALIB_OK        = 0, // прочитано, offsets и kadc обновлены
    CALIB_EMPTY     = 1, // во флеше ничего нет (прибор ни разу не сохранялся)
    CALIB_BAD       = 2, // запись есть, но не наша: сигнатура, версия или сумма
    CALIB_NOTCAL    = 3, // сохранять нечего: значения совпадают с заводскими
    CALIB_FLASH_ERR = 4, // Flash API вернул ошибку при записи или стирании
    CALIB_BUSY      = 5  // мост модулирует: операция ОТЛОЖЕНА до закрытия
                         // ключей, заявка не потеряна. Разбор - у
                         // power_par_busy() в power_par.h
} CalibStatus;

//---------------------------------------------------------------------------
// Прочитать калибровки из флеша в глобальные offsets и kadc.
//
// БЕЗОПАСНА В ЛЮБОЙ МОМЕНТ: не трогает Flash API, не стирает и не пишет -
// только читает память банка как обычные ячейки. Инициализация FAPI для неё
// не нужна, работает и в RAM-, и во flash-сборке.
//
// При CALIB_EMPTY или CALIB_BAD глобальные offsets и kadc НЕ ТРОГАЮТСЯ -
// остаётся то, что вызывающий положил туда до вызова (обычно дефолты).
//---------------------------------------------------------------------------
uint16_t calib_load(void);

//---------------------------------------------------------------------------
// Прочитать запись из флеша в *blob, НЕ ТРОГАЯ рабочие структуры. Для копии
// в мосте (bridge_store.c): уходит то, что переживёт выключение, а не то,
// что сейчас крутят в ОЗУ. Безопасна в любой момент, как и calib_load().
// Возвращает CALIB_OK, CALIB_EMPTY или CALIB_BAD.
//---------------------------------------------------------------------------
uint16_t calib_peek(CalibBlob *blob);

//---------------------------------------------------------------------------
// Восстановить настройку из копии в мосте (команда 343). w - запись целиком,
// как её отдал calib_peek(), n - её длина в словах.
//
// Принимается, только если запись наша (метка, версия, сумма) и ключи
// закрыты: та же граница, что у правки паспорта, power_par_busy(). Тогда
// раздаётся (power_par_apply) и встаёт заявка во флеш. Только из фона.
//---------------------------------------------------------------------------
#define CALIB_RESTORE_OK   0U
#define CALIB_RESTORE_SIZE 1U // не та длина - другая версия прошивки
#define CALIB_RESTORE_BAD  2U // метка, версия или сумма не сошлись
#define CALIB_RESTORE_BUSY 3U // мост модулирует

uint16_t calib_restore(const uint16_t *w, uint16_t n);

// Удачных сохранений с включения. По его изменению копия в мосте обновляется.
extern volatile uint16_t calibSaveCount;

//---------------------------------------------------------------------------
// Сохранить текущие offsets и kadc во флеш.
//
// В ОТЛИЧИЕ ОТ calib_load() ПИШЕТ ВО ФЛЕШ. Требует предварительного
// calib_store_init(). Может занять заметное время: когда банк заполнен,
// внутри происходит стирание всего банка.
//
// Звать только из фона, никогда из прерывания.
//---------------------------------------------------------------------------
uint16_t calib_save(void);

//---------------------------------------------------------------------------
// Инициализация Flash API. Нужна ТОЛЬКО перед calib_save(), для чтения не
// требуется. Вызывать один раз при старте.
//---------------------------------------------------------------------------
uint16_t calib_store_init(void);

//---------------------------------------------------------------------------
// dbg Команда сохранения из отладчика.
//
// Позвать calib_save() прямо из окна Watch нельзя: вызов со скобками требует
// ОСТАНОВЛЕННОЙ цели, а внутри идёт работа с флешем, которую нельзя прерывать
// на середине. Поэтому команда пишется числом, а функцию зовёт фоновый цикл.
// Тот же приём, что и gtCmd в grid_tie.h.
//
//   1 = сохранить текущие offsets и kadc во флеш
//   2 = стереть банк, вернуть состояние "прибор не калиброван"
//
// Фон сбрасывает переменную в 0 сам, поэтому повторное сохранение - это снова
// просто "1", без предварительного стирания значения.
//
// Результат последнего сохранения ложится в calibSaveStatus: 0 - успех.
//---------------------------------------------------------------------------
extern volatile uint16_t calibCmd;
extern uint16_t          calibSaveStatus;

// Что нашлось во флеше при старте: результат calib_load() из main().
// 0 = прочитано, 1 = флеш пуст, 2 = запись есть, но не наша (версия или сумма).
//
// Определена в main.c, а объявлена здесь: это результат работы ЭТОГО модуля, и
// искать его надо рядом с calibSaveStatus. Наружу уходит командой 698 вместе
// с ним, одним словом.
extern uint16_t calibLoadStatus;

//---------------------------------------------------------------------------
// Заявка на сохранение.
//
// Ставится ТАМ, ГДЕ КАЛИБРОВКА ДЕЙСТВИТЕЛЬНО ИЗМЕНИЛАСЬ: в обработчиках команд
// CAN 198..203 (масштабы) и в SaveAdcOffsets() (нули). Снимает её только
// calib_store_background().
//
// Раньше здесь использовался бит eeprom.bit.SaveCoef, и это было ошибкой:
// его ставит команда, а снимает обработчик SPI-EEPROM, то есть момент
// срабатывания зависел от чужой подсистемы. Плюс тот же бит ставит floatKadc()
// при инициализации - приходилось отдельными флагами отличать старт от
// команды оператора. Собственная заявка снимает обе проблемы разом:
// floatKadc() её не трогает, и никто, кроме нас, её не снимает.
//
// ЕСЛИ ДОБАВИТЕ НОВЫЙ СПОСОБ МЕНЯТЬ КАЛИБРОВКИ - поставьте здесь 1, иначе
// изменение не попадёт во флеш.
extern volatile uint16_t calibSaveReq;

// Вызывать из фонового цикла main(). Пока заявок нет, не делает ничего и
// ничего не стоит.
void calib_store_background(void);

//---------------------------------------------------------------------------
// Привести хранилище в соответствие после сброса нулей ИЛИ масштабов к
// заводским (команды CAN 206 и 213). Сама решает, что нужно: сохранить
// оставшуюся половину калибровки или стереть банк, если не осталось ничего.
//
// Звать ПОСЛЕ того, как заводские значения уже подставлены - функция смотрит
// на текущее состояние offsets.crc и kadc.crc.
//---------------------------------------------------------------------------
void calib_store_after_reset(void);

#endif /* CALIB_STORE_H_ */
