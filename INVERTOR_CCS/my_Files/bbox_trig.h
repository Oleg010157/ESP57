/*
 * bbox_trig.h
 *
 * Чёрный ящик: сторона прибора. Сам осциллограф живёт в мосте ESP32
 * (ESP32_BRIDGE/main/bbox.c): мост держит кольцо из последней секунды
 * быстрой ленты и по пуску сохраняет его во флеш. Прибору остаётся две
 * вещи:
 *
 *   1. Лента должна идти всегда. Пока пульт ленту не просит (canaKadr
 *      пуст), прибор каждый такт собирает набор F3_convertor и отдаёт его
 *      ТОЛЬКО мосту, кадром BBOX_FAST_ID: не в CAN и не дальше в сеть.
 *      Просит - мост пишет ту ленту, что идёт пульту.
 *
 *   2. Пуск. Новая авария сессии (RegisterSessionEvent) - запись BBOX_TRIG_ID
 *      мосту: код, время UTC (wall_clock.h), сессия, тип ленты и счётчик
 *      тактов в момент аварии. Шлёт её фон: аварии поднимаются и из
 *      прерываний, а очередь к мосту - дело фона.
 *
 * Ошибки связи CAN (28..31) и памяти (50..59) запись не запускают: они о
 * прошлом не говорят ничего, а места во флеше моста четыре.
 *
 * Команда 339 - пуск вручную, для проверки. Код в записи - 0xFFFF.
 *
 * Формат - docs/esp32-spi-protocol-RU.md, раздел «Чёрный ящик».
 */

#ifndef BBOX_TRIG_H_
#define BBOX_TRIG_H_

#include <stdint.h>

#define BBOX_FAST_ID   0x7E1U // кадр ленты для чёрного ящика, только мосту
#define BBOX_TRIG_ID   0x7E2U // пуск записи
#define BBOX_CMD       339U   // команда пульта: пуск вручную
#define BBOX_CODE_HAND 0xFFFFU

// Из RegisterSessionEvent(), на новую аварию сессии. Можно из прерывания.
void BBox_onEvent(uint16_t code);

// Пуск вручную - команда 339.
void BBox_manual(void);

// Из фона: отправить пуск, если он есть.
void BBox_background(void);

// Тип ленты 103 по canaKadr - код команды 1001 (1, 2, 3, 4, 6), 0 - ленты нет.
uint16_t BBox_frameType(void);

#endif /* BBOX_TRIG_H_ */
