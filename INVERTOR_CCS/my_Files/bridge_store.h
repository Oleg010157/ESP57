/*
 * bridge_store.h
 *
 * Мост ESP32 как второе хранилище прибора: длинный журнал событий и копия
 * настройки. Своё хранилище прибора остаётся главным - EEPROM с историей
 * аварий (nv_store.c) и флеш с настройкой (calib_store.c): прибор работает и
 * без моста. Мост добавляет то, чего у них нет:
 *
 *   ЖУРНАЛ. Каждое новое событие сессии (RegisterSessionEvent) - отдельной
 *   строкой: код, время UTC, сессия. В EEPROM прибора на код только счётчик и
 *   последний раз; кто за кем шёл и сколько раз за неделю, видно только тут.
 *   Повторы одного кода чаще раза в минуту мост сворачивает в счётчик.
 *
 *   КОПИЯ НАСТРОЙКИ. Запись CalibBlob (нули и масштабы АЦП, паспорт силовой
 *   части, коэффициенты регуляторов) - такая, как она лежит во флеше, с
 *   уникальным номером кристалла. Уходит мосту при включении, после каждого
 *   сохранения и по просьбе (команда 341: её даёт мост, поднявшись, и пульт).
 *   Пустую или чужую запись мост в копию не берёт: новая плата не затрёт
 *   копию старой.
 *
 *   ВОССТАНОВЛЕНИЕ - только вручную, с пульта: команды 342 (слова записи) и
 *   343 (принять). Прибор проверяет запись и берёт её, только когда ключи
 *   закрыты; ответ - ACK 343, d3 = CALIB_RESTORE_* (calib_store.h).
 *
 * Формат - docs/esp32-spi-protocol-RU.md, раздел «Журнал и копия настройки».
 */

#ifndef BRIDGE_STORE_H_
#define BRIDGE_STORE_H_

#include <stdint.h>

#define BST_ID_EVENT    0x7D1U // событие журнала: код, UTC мл., UTC ст., сессия
#define BST_ID_CAL_HDR  0x7D2U // копия настройки: заголовок
#define BST_ID_CAL_DATA 0x7D3U // копия настройки: смещение и до 30 слов

#define BST_CMD_SEND    341U // прислать копию настройки
#define BST_CMD_WORDS   342U // восстановление: d3 - смещение, d1, d2 - два слова
#define BST_CMD_APPLY   343U // восстановление: d1 - длина в словах; ответ d3 - итог

// Причина отправки копии - в заголовке.
#define BST_WHY_BOOT  0U
#define BST_WHY_SAVED 1U
#define BST_WHY_ASKED 2U

// Из RegisterSessionEvent() на новое событие сессии. Можно из прерывания.
void BridgeStore_onEvent(uint16_t code);

// Из cmd_MBOX28 - может быть и прерывание MCAN.
void BridgeStore_cmd(uint16_t cmd, uint16_t d1, uint16_t d2, uint16_t d3);

// Из фона.
void BridgeStore_background(void);

#endif /* BRIDGE_STORE_H_ */
