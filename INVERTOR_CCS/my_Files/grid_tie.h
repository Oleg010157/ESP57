#ifndef GRID_TIE_H_
#define GRID_TIE_H_

#include <stdint.h>

//---------------------------------------------------------------------------
// Состояния автомата подключения к сети
//---------------------------------------------------------------------------
enum GridState
{
    GT_OFF   = 0, // мост закрыт, Iset = 0
    GT_SYNC  = 1, // ждём качественного захвата PLL
    GT_RAMP  = 2, // Iset плавно идёт от 0 к уставке
    GT_RUN   = 3, // рабочий режим
    GT_FAULT = 4  // авария, мост закрыт до ручного сброса
};

//---------------------------------------------------------------------------
// PR (proportional-resonant) регулятор тока.
//
// Резонансная часть - пара связанных интеграторов, вращающихся ровно с шагом
// step за такт. step берётся из sineB.step, то есть резонанс автоматически
// сидит на частоте сети и едет за ней, без единого вызова sinf/cosf.
//
// leak делает регулятор неидеальным: усиление на резонансе конечно. Без него
// пара интеграторов - незатухающий генератор, и любая накопленная энергия
// остаётся в нём навсегда.
//---------------------------------------------------------------------------
struct PRreg
{
    float Kp;   // пропорциональная часть, В/А
    float Ki;   // резонансная часть, В/(А*с)
    float KiTs; // Ki * Ts - пересчитывается раз за период сети
    float leak; // затухание резонанса за такт, 0.002 -> добротность ~500
    float step; // угол поворота за такт, рад (= sineB.step)
    float x1;   // состояние резонатора, оно же выход резонансной части
    float x2;   // квадратурное состояние
    float xMax; // ограничение |x1| (анти-виндап), В
    float out;  // dbg последний выход
};

//---------------------------------------------------------------------------
// Всё хозяйство сетевого режима в одной структуре: смотреть и крутить
// в отладчике на живой цели удобнее одним объектом.
//---------------------------------------------------------------------------
struct GridTie
{
    //--- состояние -------------------------------------------------------
    uint16_t State;      // enum GridState
    uint16_t fault;      // код последней аварии (0 - не было)
    uint16_t faultNew;   // 1 = аварию ещё не зарегистрировали в журнале
    uint16_t shutdownReq; // 1 = фон должен закрыть IGBT (см. grid_tie_background)
    uint16_t syncCnt;    // счётчик подряд идущих хороших периодов сети
    uint16_t syncNeed;   // сколько их нужно для перехода GT_SYNC -> GT_RAMP
    uint16_t startDelay; // тактов до пуска после захвата: четверть периода сети

    // Контактор переменного тока между трансформатором и сетью.
    // В GT_SYNC он РАЗОМКНУТ, а мост уже модулирует: набирает сетевое
    // напряжение вхолостую. Замкнуть контактор при обесточенном мосте -
    // это короткое замыкание через индуктивность рассеяния.
    // Пока GPIO под реле не выделен, флаг живёт только в модели.
    uint16_t acContactor; // 0 = разомкнут, 1 = замкнут

    //--- уставка ---------------------------------------------------------
    float IsetRef;  // ЧТО хотим отдать: амплитуда тока в сеть, А
    float Iset;     // ЧТО отдаём сейчас: после нарастания, А
    float IsetSlew; // скорость нарастания, А за период сети
    float Iq;       // реактивная составляющая (по cos), А. 0 = чистая активная

    //--- измерения -------------------------------------------------------
    float uGrid; // мгновенное напряжение сети (вторичка), В
    float Udc;   // мгновенное напряжение АКБ, В - то, чем делим при расчёте m
    float iPri;  // ток первички (Ia), А
    float iSec;  // ток вторички = ток в сеть (Ib), А

    // Udc берётся мгновенным, не сглаженным: однофазный мост тянет из АКБ
    // мощность с пульсацией 100 Гц, и прямая связь обязана её видеть.
    uint16_t UdcSrc;   // 0 = константа UdcFixed (стенд), 1 = канал Vin
    float    UdcFixed; // подставное значение, В

    int16_t uGridKod; // dbg сырые знаковые отсчёты
    int16_t iPriKod;
    int16_t iSecKod;

    //--- масштабы --------------------------------------------------------
    // Ноль канала U220 в кодах АЦП. НЕ берётся из ADCPPB1RESULT: в PPB1
    // лежит калибровочный офсет (offsets.Udc = 110), а не середина шкалы,
    // поэтому "знаковый" результат PPB содержит смещение почти в 2000 кодов.
    // Вместо этого ноль берётся как середина вилки огибающей из myADC.c -
    // она измеряется по реальному сигналу и подстраивается сама.
    float u220Zero;
    float kU220; // В на код для канала U220 (в kadc такого канала нет)
    float n;     // коэффициент трансформации Uвтор/Uперв
    float iSign; // +1 или -1: полярность датчиков тока относительно "в сеть"

    //--- контур тока -----------------------------------------------------
    struct PRreg pr;
    float        iref;  // dbg заданный мгновенный ток, А
    float        ierr;  // dbg ошибка тока, А
    float        uSec;  // dbg требуемое напряжение на вторичке, В
    float        m;     // dbg индекс модуляции, -1..+1
    float        mMax;  // потолок |m|, 0.95

    //--- контур подавления постоянной составляющей -----------------------
    // Живёт на первичке: только там виден ток намагничивания и уход потока.
    float    mDC;      // поправка к m, безразмерная
    float    kDC;      // коэффициент контура
    float    mDCmax;   // жёсткий потолок |mDC|
    float    iPriAcc;  // накопитель среднего iPri за период сети
    uint16_t iPriCnt;  // сколько отсчётов накоплено
    float    iPriMean; // dbg среднее за прошлый период, А

    //--- защиты ----------------------------------------------------------
    float    ImaxPri;   // отсечка по току первички, А
    float    ImaxSec;   // отсечка по току вторички, А
    float    UdcMin;    // окно напряжения АКБ, В
    float    UdcMax;
    float    freqMin;   // окно частоты сети, Гц
    float    freqMax;
    float    ampMin;    // окно амплитуды сети, коды АЦП
    float    ampMax;
    float    phaseOk;   // допустимая |phaseErr| для признания синхронизма
    uint16_t satCount;  // тактов в упоре по m за текущий период сети
    uint16_t satLimit;  // сколько допустимо, прежде чем это авария
    uint16_t satLast;   // dbg satCount за прошлый период
    uint16_t noGrid;    // сторож пропажи сети: тактов без захвата eCAP
    uint16_t noGridMax; // порог сторожа, тактов

    //--- служебное -------------------------------------------------------
    float    Ts;     // период дискретизации контура, с
    uint16_t refSrc; // 0 = опора daca (стенд), 1 = измеренный U220 (реальная сеть)

    //--- модель для отладки без железа -----------------------------------
    uint16_t simPlant;   // 1 = токи берём из модели, а не из АЦП
    float    Lsim;       // индуктивность рассеяния, приведённая к вторичке, Гн
    float    Rsim;       // активное сопротивление там же, Ом
    float    iSim;       // ток вторички по модели, А
    // Искусственная постоянная составляющая в приложенном напряжении, В.
    // Именно так ведёт себя асимметрия мёртвого времени - это ошибка
    // НАПРЯЖЕНИЯ, а не измерения. Смещение, внесённое в измерение тока,
    // контур занулить не смог бы в принципе: он лишь упёрся бы в mDCmax.
    float    uDCinject;
    float    uSecApplied; // dbg что мост реально приложил к вторичке, В
};

extern struct GridTie gt;
extern uint16_t       gridMode; // 0 = старый режим синусоиды, 1 = сетевой

void grid_tie_init(void);
void grid_tie_step(void);       // каждое прерывание EPWM1 (5 кГц)
void grid_tie_onGridZero(void); // раз за период сети, из ECAP ISR
void grid_tie_background(void); // из фонового цикла main(): всё, чему не место в ISR
void grid_tie_fault(uint16_t code);
void grid_tie_start(void);      // запрос пуска: GT_OFF -> GT_SYNC
void grid_tie_stop(void);       // остановка в GT_OFF, сброс аварии

#endif /* GRID_TIE_H_ */
