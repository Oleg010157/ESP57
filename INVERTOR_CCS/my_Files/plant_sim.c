#include "board.h"
#include "F28P55x_Device.h"

#include "KSP.h"        // motors[] - состояние ключей
#include "myADC.h"      // kadcf - масштабы каналов АЦП
#include "cla_shared.h" // измеренные величины всех каналов
#include "1ph_Sin.h"    // cmpaA / cmpaB - то, что реально стоит в компараторах
#include "grid_tie.h"   // gt.acContactor, gt.uGrid, gt.iSign
#include "plant_sim.h"

struct Plant sim;

// TBCLK1 = 150 МГц / 2 (HSPCLKDIV = 2 по сбросу) = 75 МГц, режим UP_DOWN даёт
// 2*TBPRD тактов на период. Отсюда Ts = TBPRD / 37.5e6. Та же константа
// и в grid_tie.c: там она нужна контуру, здесь модели.
#define TB1_TICKS_PER_SECOND_HALF 37.5e6f

// Нижний предел индуктивности в знаменателе. Ноль там - это мгновенный скачок
// тока до бесконечности за один такт, то есть NaN во всех шести каналах и
// вставший прибор. Один микрогенри вместо нуля даёт заведомо быстрый, но
// конечный переходный процесс - в нём хотя бы видно, что параметр не задан.
#define L_MIN 1e-6f

//---------------------------------------------------------------------------
// Значения по умолчанию - тот же стенд, что был зашит в grid_tie_init():
// АКБ 48 В, трансформатор 1:7 с рассеянием 8 мГн и активным 0.5 Ом.
//
// Нагрузка по умолчанию ВЫКЛЮЧЕНА, и это не осторожность, а совместимость:
// при холостом ходе и разомкнутом контакторе модель ведёт себя ровно так,
// как прежняя (ток вторички тождественно ноль), и прогнанные на ней опыты
// из grid_tie.txt повторяются числом в число.
//
// Lmag = 1.4 Гн - порядок для трансформатора 3 кВт 220 В: ток намагничивания
// около 0.5 А действующего, то есть 1.5 % от номинала 13.6 А. Уточнять его
// незачем до тех пор, пока не появится настоящий сердечник.
//---------------------------------------------------------------------------
void plant_sim_init(void)
{
    sim.on       = 1U; // железа нет, работаем на модели
    sim.loadType = LOAD_OFF;

    sim.Udc = 48.0f;

    sim.n     = 7.0f;
    sim.Lleak = 0.008f;
    sim.Rwind = 0.5f;
    sim.Lmag  = 1.4f;

    sim.Rload = 16.0f; // 3 кВт при 220 В
    sim.Lload = 0.0f;

    sim.uDCinject = 0.0f;

    sim.iSec = 0.0f;
    sim.iMag = 0.0f;

    sim.m       = 0.0f;
    sim.uBridge = 0.0f;
    sim.uSecOut = 0.0f;
    sim.iPri    = 0.0f;
    sim.iBat    = 0.0f;
    sim.Ts      = 200e-6f;

    simOn = sim.on;
}

//---------------------------------------------------------------------------
// Физическая величина обратно в коды АЦП.
//
// Нужно ради ключа телеметрии TELE_KOD: в этом положении кадр 140 везёт сырые
// коды, и на модели они обязаны сойтись с мгновенными значениями, иначе
// переключение набора выглядит как поломка канала.
//
// Масштаб нулевой до первого floatKadc() и у нетарированного канала - тогда
// отдаём ноль, а не бесконечность.
//---------------------------------------------------------------------------
static inline int16_t to_kod(float value, float k)
{
    if ((k > 1e-9f) || (k < -1e-9f))
        return (int16_t)(value / k);

    return 0;
}

//---------------------------------------------------------------------------
// Такт модели. Вызывается из INT_myADCB_1_ISR сразу за чтением токов с АЦП и
// ДО такта управления - см. комментарий в plant_sim.h.
//
// Уравнения (всё приведено ко вторичке, то есть к стороне 220 В):
//
//     m        = (cmpaB - cmpaA) / TBPRD          что стоит в компараторах
//     uBridge  = n * m * Udc + uDCinject          что мост приложил
//     di/dt    = (uBridge - emf - R*i) / L        ток вторички
//     iMag    += uBridge * Ts / Lmag              ток намагничивания
//     iPri     = n * (iSec + iMag)
//     iBat     = m * iPri                         баланс мощности моста
//
// Ветвь намагничивания стоит у ЗАЖИМОВ МОСТА, а не за рассеянием: это Г-схема
// замещения, точная при отнесении всего рассеяния к выходу. Разница с Т-схемой
// - падение на рассеянии, единицы вольт из трёх сотен, и ради неё пришлось бы
// решать систему из двух связанных состояний в каждом такте.
//---------------------------------------------------------------------------
// В .TI.ramfunc эта функция НЕ кладётся, в отличие от соседей по прерыванию.
//
// Секция привязана к одному блоку RAMLS0 (0x800 слов), и он уже почти полон:
// модель туда не влезает. Отбирать место у контура тока ради неё неправильно -
// на живом железе модель выключена и выходит из функции по первому же
// сравнению. Работать из флеша ей придётся ровно в том случае, когда прибор
// и так стоит на столе, а не в сети, и лишние такты безразличны.
void plant_sim_step(void)
{
    // Ключ для CLA ставится ПЕРВЫМ делом и безусловно: выключенная модель
    // обязана вернуть задаче три канала, а не оставить её стоять в стороне.
    simOn = sim.on;

    if (!sim.on)
        return;

    float tbprd = (float)EPwm1Regs.TBPRD;

    sim.Ts = tbprd * (1.0f / TB1_TICKS_PER_SECOND_HALF);

    //-----------------------------------------------------------------
    // 1. Что мост приложил за ПРОШЕДШИЙ такт.
    //
    // Берём не gt.m и не sineB.gain, а сами компараторы: там лежит то, что
    // отработало железо, вместе с усечением float->uint16. Одна формула на
    // оба режима моста - и контур тока, и sine_invertor2() оставляют в cmpaA
    // и cmpaB значения, разность которых и есть индекс модуляции.
    //-----------------------------------------------------------------
    sim.m = (tbprd > 1.0f) ? (((float)cmpaB - (float)cmpaA) / tbprd) : 0.0f;

    // Ключи закрыты - обмотка разомкнута, и оба тока равны нулю по
    // определению. Остаточный поток сердечника модель не помнит: после
    // включения ключей намагничивание начинается с нуля.
    if (motors[0]->flag.bit.pwm_On == 0)
    {
        sim.m       = 0.0f;
        sim.iSec    = 0.0f;
        sim.iMag    = 0.0f;
        sim.uBridge = 0.0f;
        sim.uSecOut = 0.0f;
        sim.iPri    = 0.0f;
        sim.iBat    = 0.0f;
    }
    else
    {
        sim.uBridge = sim.n * sim.m * sim.Udc + sim.uDCinject;

        //-----------------------------------------------------------------
        // 2. Ток вторички.
        //
        // Контактор замкнут - нагрузкой служит СЕТЬ, и в цепи только
        // рассеяние трансформатора: ток определяется разностью напряжений
        // моста и сети. Нагрузка при этом не моделируется - в сети мост
        // работает источником тока, и своя нагрузка на его выходе к делу
        // отношения не имеет.
        //
        // Контактор разомкнут - мост работает на собственную нагрузку
        // (режим АИН), и это единственный режим, где нагрузка вообще есть.
        //-----------------------------------------------------------------
        float r    = sim.Rwind;
        float l    = sim.Lleak;
        float emf  = 0.0f;
        float dIdt = 0.0f;

        if (gt.acContactor)
        {
            emf = gt.uGrid;
        }
        else if (sim.loadType == LOAD_OFF)
        {
            // Холостой ход: цепи нет. Ток вторички тождественно ноль, но
            // ток намагничивания ниже считается - это и есть ток холостого
            // хода трансформатора, он течёт и без нагрузки.
            sim.iSec = 0.0f;
            r        = 0.0f;
            l        = -1.0f; // признак "интегрировать нечего"
        }
        else
        {
            r += sim.Rload;
            if (sim.loadType == LOAD_RL)
                l += sim.Lload;
        }

        if (l >= 0.0f)
        {
            if (l < L_MIN)
                l = L_MIN;

            // Падения считаются по току НАЧАЛА такта - тому, что реально тёк,
            // пока к обмотке было приложено uBridge.
            dIdt = (sim.uBridge - emf - r * sim.iSec) / l;
            sim.iSec += dIdt * sim.Ts;
        }

        //-----------------------------------------------------------------
        // 3. Ток намагничивания - интеграл приложенного напряжения.
        //
        // Ради него модель и переписана: постоянная составляющая в uBridge
        // уходит сюда линейно и нарастает без предела, ровно как поток в
        // сердечнике. Контур подавления DC ловит её в среднем токе первички.
        // Насыщения в модели нет: при уходе в него настоящая Lmag рухнет
        // на порядок, здесь она останется прежней.
        //-----------------------------------------------------------------
        if (sim.Lmag > L_MIN)
            sim.iMag += sim.uBridge * (sim.Ts / sim.Lmag);
        else
            sim.iMag = 0.0f;

        //-----------------------------------------------------------------
        // 4. Что увидели бы датчики.
        //-----------------------------------------------------------------
        sim.uSecOut = sim.uBridge - sim.Rwind * sim.iSec - sim.Lleak * dIdt;
        sim.iPri    = (sim.iSec + sim.iMag) * sim.n;

        // Баланс мощности идеального моста: P = m*Udc*iPri = Udc*iBat.
        // Пульсация 100 Гц в токе АКБ отсюда и берётся - она не добавлена
        // руками, а следует из произведения двух синусоид.
        sim.iBat = sim.m * sim.iPri;
    }

    //-----------------------------------------------------------------
    // 5. Подмена измерений.
    //
    // Токи первички и вторички читает контур в этом же прерывании, поэтому
    // их пишем здесь. Три канала CLA (iBat, uBat, uSec) она сама считать не
    // будет - её держит ключ simOn, см. CLA/Task1.cla.
    //
    // Коды считаются обратным пересчётом через те же kadcf и gt.iSign, по
    // которым xfmr_currents_from_adc() и Cla1Task1 переводят коды в величины.
    //-----------------------------------------------------------------
    iPri_amp = sim.iPri;
    iSec_amp = sim.iSec;
    iPri_kod = to_kod(sim.iPri, gt.iSign * kadcf.iPri);
    iSec_kod = to_kod(sim.iSec, gt.iSign * kadcf.iSec);

    uSec_volt = sim.uSecOut;
    uSec_kod  = to_kod(sim.uSecOut, kadcf.uSec);

    uBat_volt = sim.Udc;
    uBat_kod  = to_kod(sim.Udc, kadcf.uBat);

    iBat_amp = sim.iBat;
    iBat_kod = to_kod(sim.iBat, kadcf.iBat);
}
