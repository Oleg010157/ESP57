/*
 * energy.h
 *
 * Счётчики энергии на выходе инвертора, Вт·ч. С 13.11.2026.
 *
 * Мощность - P, та же, что в слове 17 кадра 140 (pSec, считает CLA раз за
 * период сети по uSec и iSec). Знак разводит её на два счётчика:
 *
 *   ENERGY_OUT  отдано  (P > 0) - в сеть или нагрузке;
 *   ENERGY_IN   принято (P < 0) - обратно, из сети;
 *
 * и у каждого два вида: «всего» - не сбрасывается никогда, и «с последнего
 * сброса» (ENERGY_*_TRIP) - как суточный пробег у машины, обнуляется командой.
 *
 * Считаем только при открытых ключах (pwm_On): в слежении за сетью uSec есть,
 * а тока нет, и шум P в несколько ватт за сутки набежал бы в десятые доли
 * кВт·ч, которых не было.
 *
 * Шаг - раз в 50 мс, по таймеру фона: P - уже среднее за период сети, и
 * погрешность выборки в сумме за часы уходит в ноль.
 *
 * Хранятся в той же памяти I2C, что история аварий (nv_store.c, с 0x0700):
 * раз в 10 минут, сразу после закрытия ключей и после сброса. Снятие питания
 * теряет не больше 10 минут счёта; доли ватт-часа живут только в ОЗУ.
 *
 * Команда ENERGY_CMD: d1 = 0 - прочитать; d1 = 1, d2 = 3333 - обнулить «с
 * последнего сброса». Ответ - четыре ACK: d1 - номер счётчика (ENERGY_*),
 * d2 - младшее, d3 - старшее слово Вт·ч.
 */

#ifndef ENERGY_H_
#define ENERGY_H_

#include <stdint.h>

#define ENERGY_CMD 345U

enum
{
    ENERGY_OUT,      // отдано, всего
    ENERGY_IN,       // принято, всего
    ENERGY_OUT_TRIP, // отдано с последнего сброса
    ENERGY_IN_TRIP,  // принято с последнего сброса
    ENERGY_N
};

// Вт·ч, по ENERGY_*. Смотреть в Watch; пишут только energy.c и nv_store.c.
extern volatile uint32_t energyWh[ENERGY_N];

// Из таймера фона, раз в 50 мс.
void Energy_tick50ms(void);

// Из 1-секундного тика фона: раз в 10 минут - на запись.
void Energy_tick1s(void);

// Команда ENERGY_CMD (MBOX28.c).
void Energy_cmd(uint16_t d1, uint16_t d2);

#endif /* ENERGY_H_ */
