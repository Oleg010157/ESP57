/*
 * wall_clock.h
 *
 * Дата и время для журнала аварий.
 *
 * Своих часов у F28P55x нет (docs/eeprom-fram-comparison-RU.md), и до
 * 10.11.2026 запись журнала была привязана только к номеру сессии. Теперь
 * время приходит от пульта командой 337 при подключении - одинаково по CAN и
 * через WiFi-мост, мост передаёт её насквозь. Дальше прибор считает секунды
 * сам, по 1-секундному тику фона.
 *
 * Пока пульт с момента включения не подключался, время неизвестно, и журнал
 * пишет 0: запись остаётся привязана к номеру сессии, как раньше.
 *
 * Время - UTC, секунды с 1970 года. В местное переводит пульт.
 */

#ifndef WALL_CLOCK_H_
#define WALL_CLOCK_H_

#include <stdint.h>

#define WALL_CLOCK_CMD 337U // команда пульта: d1 - младшее, d2 - старшее слово UTC

// Время от пульта. Из фона (команды разбираются там или в прерывании MCAN).
void WallClock_set(uint32_t utc);

// Из 1-секундного тика фона.
void WallClock_tick1s(void);

// Текущее UTC, 0 - неизвестно. Можно звать откуда угодно, и из прерывания:
// 32-битное чтение на C28x одно, разорваться не может.
uint32_t WallClock_now(void);

#endif /* WALL_CLOCK_H_ */
