// cla_shared.c
//
// ЕДИНОЕ МЕСТО ОБЪЯВЛЕНИЯ ВСЕХ ИЗМЕРЕННЫХ ВЕЛИЧИН АЦП.
//
// Шесть каналов, по одной группе на канал, в том же порядке, что в ADCpar и
// kADCf (myADC.h): iPri, iSec, iBat, u220, uBat, uSec. Раньше объявления были
// раскиданы - токи в 1ph_Sin.c, сеть в myADC.c, звено в структуре dc, - и
// понять, что вообще меряется и чем, можно было только обыскав проект.
//
// Переменные плоские, а не поля структур. Причина видна в Task1.cla: тело
// задачи почти целиком фильтры вида
//     uBat_rf = 0.9f * uBat_rf + 0.1f * uBat_volt;
// и с точечной нотацией (dc.Udc_rf = 0.9f * dc.Udc_rf + ...) такие строки
// перестают читаться.
//
// РАЗМЕЩЕНИЕ ОДНО НА ВСЕХ: #pragma DATA_SECTION(x, "cla_shared") у каждой
// переменной. Секция лежит в RAMLS2, который SysConfig отдаёт как CPU/CLA
// shared data memory (memcfg: LS2 = CLA_data) - этот режим оставляет полный
// доступ на чтение и запись обеим сторонам. То есть любой канал виден и CPU,
// и CLA независимо от того, кто его считает.
//
// VOLATILE - вот он как раз не у всех, и стоит ровно у тех, кого пишет CLA:
// их значение меняется асинхронно к CPU, и без volatile компилятор имеет право
// закешировать его в регистре. У величин, которые CPU пишет сам, volatile
// только мешал бы - это горячий код контура тока, там каждое обращение к
// памяти на счету.
//
// КТО ПИШЕТ, указано в шапке каждой группы. Разбиение не случайное:
//
//   CPU пишет iPri, iSec (прерывание ADCB, EOC1) и u220 (прерывание ADCA,
//   EOC0). Отдать их CLA НЕЛЬЗЯ: Task1 запускается по ADCA INT2, взведённой на
//   EOC3 - конце последнего преобразования (~4.6 мкс от триггера), - а контур
//   тока живёт по EOC1 (~2.3 мкс) и потребляет iPri_amp/iSec_amp немедленно.
//   Стань CLA их источником - контур начал бы читать прошлый такт и вернулись
//   бы 200 мкс запаздывания, ради снятия которых такт управления и переносили
//   с прерывания EPWM1 на ADCB (разбор - комментарий перед INT_myADCB_1_ISR в
//   1ph_Sin.c). То же и с u220_kod: его читает grid_tie_step() на 2.3 мкс.
//
//   CLA пишет iBat, uBat, uSec - каналы, которые к EOC3 никому не нужны
//   срочно, и которые до этой работы либо не читались вовсе, либо читались
//   раньше времени.
//
// Здесь же раньше жил INT_myCLA7_ISR. Удалён вместе с Task7: вектор CLA1_7 в
// PIE указывает на CLA1_7_ISR из f28p55x_defaultisr.c, наш обработчик там
// никогда не стоял и не выполнялся. MainISR(), который он вызывал, вызывается
// из INT_myEPWM3_ISR (3ph_sin.c) - и продолжает.
//
// Прерывания CPU по завершению задач CLA выключены целиком (SysConfig, myCLA0:
// cpuint_CLA_TASK_1..8 = false). Task1 измерительная, её результат читают из
// фона и по отладчику, повод дёргать CPU каждые 200 мкс отсутствует.

#include "f28p55x_device.h"

#include "cla_shared.h"

//---------------------------------------------------------------------------
// Коэффициенты пересчёта кодов в физические величины, CPU -> CLA.
//
// Остались структурой, в отличие от результатов ниже: живут в CpuToCla1MsgRAM,
// у которой направление аппаратное (CPU пишет, CLA только читает), и в
// выражении дают всего один точечный член - kadcf.uBat * kod.
//---------------------------------------------------------------------------
#pragma DATA_SECTION(kadcf, "CpuToCla1MsgRAM");
volatile kADCf kadcf;

// Окно усреднения RMS в отсчётах = период сети.
//
// Копия sineB.resolution. Копия нужна потому, что сам sineB лежит в обычной
// .data (RAMLS5/6), а CLA видит только отданные ей блоки - LS1, LS2, LS7 - и
// message RAM. Лежит здесь, рядом с kadcf, а не среди результатов: это такой
// же параметр, который CPU задаёт, а CLA потребляет.
//
// Синхронизацию держит change_sine() в 1ph_Sin.c - через неё проходит ЛЮБОЕ
// изменение resolution (команды CAN 621/62x и инициализация в main.c), другого
// пути нет. Разъехаться значения не могут.
#pragma DATA_SECTION(rmsWindow, "CpuToCla1MsgRAM");
volatile uint16_t rmsWindow;

//---------------------------------------------------------------------------
// Диагностика самой CLA: длительность Cla1Task1 в тактах EPWM7 (1/150 мкс).
//
// Лежит в Cla1ToCpuMsgRAM, а не среди результатов в cla_shared, по смыслу:
// это не измеренная величина, а сведения о работе задачи, и направление у них
// строго CLA -> CPU. Для этого направления есть выделенный блок, до сих пор
// пустовавший. Шаблон - тот же, что у TI в примерах CLA (fResult в
// cla_ex1_asin.c): объявление в C-файле, запись из .cla-задачи.
//
// Доступ к этому блоку несимметричный: CLA читает и пишет, CPU только читает.
// Задаче этого хватает - task1Start она и пишет, и читает сама. На обнуление
// при старте не рассчитываем: обе величины задача переписывает каждый вызов.
//
// task1Time на такте закрытия окна RMS заметно больше обычного - там четыре
// деления и четыре корня. Смотреть надо именно на этот пик, а не на среднее.
//---------------------------------------------------------------------------
#pragma DATA_SECTION(task1Start, "Cla1ToCpuMsgRAM");
#pragma DATA_SECTION(task1Time, "Cla1ToCpuMsgRAM");
volatile uint16_t task1Start;
volatile uint16_t task1Time;

//---------------------------------------------------------------------------
// 1. iPri - ток первичной обмотки.  B1, ADCB SOC0/PPB1, масштаб kadcf.iPri
//    Мгновенные значения пишет CPU: xfmr_currents_from_adc() в 1ph_Sin.c,
//    прерывание ADCB по EOC1. Действующее считает CLA, см. ниже.
//---------------------------------------------------------------------------
#pragma DATA_SECTION(iPri_kod, "cla_shared");
#pragma DATA_SECTION(iPri_amp, "cla_shared");
#pragma DATA_SECTION(iPri_rms, "cla_shared");
int16_t          iPri_kod;
float            iPri_amp;
volatile float   iPri_rms; // пишет CLA

//---------------------------------------------------------------------------
// 2. iSec - ток вторичной обмотки (ток в сеть).  B4, ADCB SOC1/PPB2, kadcf.iSec
//    Так же: мгновенные - CPU, действующее - CLA.
//---------------------------------------------------------------------------
#pragma DATA_SECTION(iSec_kod, "cla_shared");
#pragma DATA_SECTION(iSec_amp, "cla_shared");
#pragma DATA_SECTION(iSec_rms, "cla_shared");
int16_t          iSec_kod;
float            iSec_amp;
volatile float   iSec_rms; // пишет CLA

//---------------------------------------------------------------------------
// 3. iBat - ток АКБ.  A12, ADCA SOC2/PPB3, масштаб kadcf.iBat
//    Пишет CLA (Cla1Task1). До этой работы канал не читал никто.
//---------------------------------------------------------------------------
#pragma DATA_SECTION(iBat_kod, "cla_shared");
#pragma DATA_SECTION(iBat_amp, "cla_shared");
#pragma DATA_SECTION(iBat_rf, "cla_shared");
volatile int16_t iBat_kod;
volatile float   iBat_amp;
volatile float   iBat_rf;

//---------------------------------------------------------------------------
// 4. u220 - напряжение сети после контактора.  A0, ADCA SOC0/PPB1
//    Пишет CPU: INT_myADCA_1_ISR в myADC.c, по EOC0.
//
//    Отсчёт СЫРОЙ, не через PPB1: в ADCPPB1OFFREF лежит калибровочный ноль
//    канала (~110), а не середина шкалы, поэтому "знаковый" результат PPB нёс
//    бы постоянное смещение почти в 2000 кодов. Ноль вычитает grid_tie_step()
//    через gt.u220Zero - середину вилки огибающей.
//
//    u220amp - половина раствора вилки u220hi_kod/u220low_kod, то есть
//    амплитуда сети в кодах. Саму вилку ведёт та же INT_myADCA_1_ISR.
//    Масштаба в kadc для этого канала нет, вольты считает gt.kU220.
//
//    u220_volt - мгновенное значение в вольтах, ноль взят как середина вилки.
//    Не путать с gt.uGrid: та же величина, но с нулём gt.u220Zero, который
//    обновляется раз за период и только в gridMode - контуру нужен ноль без
//    дрожания. u220_volt верен в обоих режимах, разбор - в myADC.c.
//
//    u220_rms - действующее за период сети, считает CLA.
//---------------------------------------------------------------------------
#pragma DATA_SECTION(u220_kod, "cla_shared");
#pragma DATA_SECTION(u220amp, "cla_shared");
#pragma DATA_SECTION(u220_volt, "cla_shared");
#pragma DATA_SECTION(u220_rms, "cla_shared");
uint16_t         u220_kod;
float            u220amp;
float            u220_volt;
volatile float   u220_rms; // пишет CLA

//---------------------------------------------------------------------------
// 5. uBat - напряжение АКБ, оно же напряжение звена постоянного тока на входе
//    моста.  A4, ADCA SOC1/PPB2, масштаб kadcf.uBat
//    Пишет CLA (Cla1Task1).
//
//    Тот же канал читает inline grid_tie_step() в gt.Udc (grid_tie.c) - по
//    расхождению uBat_volt с gt.Udc и проверяется, что CLA считает верно.
//    В gt.Udc он остаётся мгновенным намеренно, см. комментарий в grid_tie.h:
//    однофазный мост тянет из АКБ мощность с пульсацией 100 Гц, и прямая связь
//    обязана её видеть, а uBat_rf сглажен.
//---------------------------------------------------------------------------
#pragma DATA_SECTION(uBat_kod, "cla_shared");
#pragma DATA_SECTION(uBat_volt, "cla_shared");
#pragma DATA_SECTION(uBat_rf, "cla_shared");
volatile int16_t uBat_kod;
volatile float   uBat_volt;
volatile float   uBat_rf;

//---------------------------------------------------------------------------
// 6. uSec - напряжение на выходе инвертора, до контактора.
//    A1, ADCA SOC3/PPB4, масштаб kadcf.uSec
//    Пишет CLA (Cla1Task1).
//
//    Раньше его читала INT_myADCA_1_ISR, а та взведена на EOC0 - то есть
//    значение брали на такт раньше, чем SOC3 успевал преобразоваться. У CLA
//    триггер стоит как раз на EOC3, это и есть момент готовности канала.
//
//    ВНИМАНИЕ: пока DBG_SIN_DAC = 1, на этот пин изнутри выводит отладочную
//    синусоиду CMPSS1 через COMPDACL, то есть канал меряет собственный ЦАП, а
//    не датчик. Для проверки тракта измерения это полноценный сигнал.
//
//---------------------------------------------------------------------------
#pragma DATA_SECTION(uSec_kod, "cla_shared");
#pragma DATA_SECTION(uSec_volt, "cla_shared");
#pragma DATA_SECTION(uSec_rms, "cla_shared");
volatile int16_t uSec_kod;
volatile float   uSec_volt;
volatile float   uSec_rms;

//---------------------------------------------------------------------------
// Сброс сглаживающих фильтров CLA.
//
// При старте секция и так обнуляется загрузчиком (.cinit, zero_init), так что
// ради первого включения функция не нужна. Нужна она как явная точка сброса:
// вызывается из main() при инициализации и годится, чтобы обнулить накопленное
// после аварии, не перезагружая прибор.
//
// Величины, которые пишет CPU, здесь не трогаем: у них свои точки сброса.
//---------------------------------------------------------------------------
void CLA_shared_Init(void)
{
    iBat_kod = 0;
    iBat_amp = 0.0f;
    iBat_rf  = 0.0f;

    uBat_kod  = 0;
    uBat_volt = 0.0f;
    uBat_rf   = 0.0f;

    uSec_kod  = 0;
    uSec_volt = 0.0f;
}
